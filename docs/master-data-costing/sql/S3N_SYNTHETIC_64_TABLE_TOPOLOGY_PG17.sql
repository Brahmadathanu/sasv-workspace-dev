-- S3N synthetic-only FK topology extender. Existing PG17 CI fixture only.
-- Adds exactly 61 extra directly run-linked relations to existing 3:
-- 55 additional with PK, 6 additional keyless (plus keyless designation = 7).
-- Adds 62 internal child->parent FKs entirely within the 64 relations.
-- Zero production data and zero rows in all 61 new relations.
DO $synthetic$
DECLARE i int; table_name text; with_primary_key boolean;
BEGIN
  FOR i IN 1..61 LOOP
    with_primary_key := i > 6;
    table_name:=CASE WHEN with_primary_key THEN
       's3n_pk_'||lpad(i::text,2,'0') ELSE
       's3n_keyless_'||lpad(i::text,2,'0') END;
    IF with_primary_key THEN
      EXECUTE format(
       'CREATE TABLE costing.%I (
         id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
         refresh_run_id bigint REFERENCES costing.costing_refresh_run(id),
         parent_evidence_id bigint REFERENCES costing.marketing_signed_billed_sales_evidence_snapshot(id),
         placeholder text)',table_name
      );
    ELSE
      EXECUTE format(
       'CREATE TABLE costing.%I (
         refresh_run_id bigint REFERENCES costing.costing_refresh_run(id),
         parent_evidence_id bigint REFERENCES costing.marketing_signed_billed_sales_evidence_snapshot(id),
         placeholder text)',table_name
      );
    END IF;
  END LOOP;
END $synthetic$;
ALTER TABLE costing.marketing_regional_sales_evidence_snapshot
  ADD COLUMN s3n_parent_evidence_id bigint
  REFERENCES costing.marketing_signed_billed_sales_evidence_snapshot(id);
DO $verify$
DECLARE direct_count integer; nested_count integer; without_pk integer; outside_edges integer;
BEGIN
  SELECT count(*) INTO direct_count
  FROM pg_constraint WHERE contype='f'
    AND confrelid='costing.costing_refresh_run'::regclass;
  IF direct_count<>64 THEN
    RAISE EXCEPTION 'Expected exactly 64 direct FKs, found %',direct_count;
  END IF;
  WITH direct AS (SELECT DISTINCT conrelid AS relid FROM pg_constraint
     WHERE contype='f' AND confrelid='costing.costing_refresh_run'::regclass)
  SELECT count(*) INTO nested_count
  FROM pg_constraint WHERE contype='f' AND confrelid IN (SELECT relid FROM direct);
  IF nested_count<>62 THEN
    RAISE EXCEPTION 'Expected 62 nested FKs, found %',nested_count;
  END IF;
  WITH direct AS (SELECT DISTINCT conrelid AS relid FROM pg_constraint
     WHERE contype='f' AND confrelid='costing.costing_refresh_run'::regclass)
  SELECT count(*) INTO without_pk FROM direct d WHERE NOT EXISTS
     (SELECT 1 FROM pg_constraint pk WHERE pk.contype='p' AND pk.conrelid=d.relid);
  IF without_pk<>7 THEN
    RAISE EXCEPTION 'Expected seven keyless relations, found %',without_pk;
  END IF;
  WITH direct AS (SELECT DISTINCT conrelid AS relid FROM pg_constraint
     WHERE contype='f' AND confrelid='costing.costing_refresh_run'::regclass)
  SELECT count(*) INTO outside_edges FROM pg_constraint
  WHERE contype='f' AND confrelid IN (SELECT relid FROM direct)
    AND conrelid NOT IN (SELECT relid FROM direct);
  IF outside_edges<>0 THEN
    RAISE EXCEPTION 'Nested FK escaping direct relation closure';
  END IF;
  RAISE NOTICE 'S3N_TOPOLOGY_PASS 64 direct, 62 nested, 7 keyless, 0 outside';
END $verify$;
