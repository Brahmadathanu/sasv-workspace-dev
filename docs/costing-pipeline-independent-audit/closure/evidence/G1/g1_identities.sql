with r as (select unnest(array[122,128]::bigint[]) run),
m as (select * from costing.sku_material_cost_snapshot where refresh_run_id in (122,128)),
p as (select * from costing.sku_prime_cost_snapshot where refresh_run_id in (122,128)),
d as (select * from costing.sku_direct_labour_allocation_snapshot where refresh_run_id in (122,128)),
o as (select * from costing.sku_overhead_allocation_snapshot where refresh_run_id in (122,128)),
c as (select * from costing.sku_manufacturing_cop_snapshot where refresh_run_id in (122,128)),
i as (select * from costing.sku_internal_loaded_cost_snapshot where refresh_run_id in (122,128)),
b as (select * from costing.sku_pricing_bridge_snapshot where refresh_run_id in (122,128)),
x as (
 select m.refresh_run_id run, m.sku_id,
  abs(m.material_cost_per_sku-(m.rm_cost_per_sku+m.pm_cost_per_sku)) e_mat,
  abs(p.material_cost_per_sku-m.material_cost_per_sku) e_mat_xfer,
  abs(p.prime_cost_per_sku-(p.material_cost_per_sku+p.direct_labour_cost_per_sku+p.internal_material_conversion_cost_per_sku)) e_prime,
  abs(p.direct_labour_cost_per_sku-d.direct_labour_cost_per_sku) e_dl_xfer,
  abs(d.direct_labour_cost_per_sku-(coalesce(d.manufacturing_direct_labour_cost_per_sku,0)+coalesce(d.packing_labour_cost_per_sku,0))) e_dl_split,
  (d.manufacturing_direct_labour_cost_per_sku is null) dl_split_null,
  abs(c.prime_cost_per_sku-p.prime_cost_per_sku) e_prime_xfer,
  abs(c.manufacturing_cop_per_sku-(c.prime_cost_per_sku+c.production_overhead_cost_per_sku+c.quality_control_overhead_cost_per_sku+c.materials_stores_overhead_cost_per_sku)) e_cop,
  abs(c.production_overhead_cost_per_sku-o.production_overhead_cost_per_sku)+abs(c.quality_control_overhead_cost_per_sku-o.quality_control_overhead_cost_per_sku)+abs(c.materials_stores_overhead_cost_per_sku-o.materials_stores_overhead_cost_per_sku) e_oh_xfer,
  abs(i.manufacturing_cop_per_sku-c.manufacturing_cop_per_sku) e_cop_xfer,
  abs(i.internal_loaded_cost_per_sku-(i.manufacturing_cop_per_sku+i.admin_overhead_cost_per_sku+i.finance_admin_overhead_cost_per_sku)) e_ilc,
  abs(i.internal_loaded_cost_per_sku-(i.material_cost_per_sku+i.direct_labour_cost_per_sku+i.production_overhead_cost_per_sku+i.quality_control_overhead_cost_per_sku+i.materials_stores_overhead_cost_per_sku+i.admin_overhead_cost_per_sku+i.finance_admin_overhead_cost_per_sku)) e_ilc_atomic_displayed,
  abs(i.internal_loaded_cost_per_sku-(i.material_cost_per_sku+i.direct_labour_cost_per_sku+p.internal_material_conversion_cost_per_sku+i.production_overhead_cost_per_sku+i.quality_control_overhead_cost_per_sku+i.materials_stores_overhead_cost_per_sku+i.admin_overhead_cost_per_sku+i.finance_admin_overhead_cost_per_sku)) e_ilc_atomic_full,
  abs(b.internal_loaded_cost_per_sku-i.internal_loaded_cost_per_sku) e_ilc_xfer,
  abs(b.pricing_cost_per_sku-(b.internal_loaded_cost_per_sku+b.marketing_expense_cost_per_sku)) e_pc,
  abs(b.pricing_cost_per_sku_ik-(b.internal_loaded_cost_per_sku+b.marketing_expense_cost_per_sku_ik)) e_pc_ik,
  abs(b.pricing_cost_per_sku_ok-(b.internal_loaded_cost_per_sku+b.marketing_expense_cost_per_sku_ok)) e_pc_ok,
  abs(b.ik_margin_amount_before_scheme-(b.mrp_ik-b.pricing_cost_per_sku_ik)) e_m_ik,
  abs(b.ok_margin_amount_before_scheme-(b.mrp_ok-b.pricing_cost_per_sku_ok)) e_m_ok,
  abs(b.ik_margin_amount_before_scheme-(b.mrp_ik-b.pricing_cost_per_sku)) e_m_ik_national,
  (d.sku_id is null) miss_d, (o.sku_id is null) miss_o, (c.sku_id is null) miss_c, (i.sku_id is null) miss_i, (b.sku_id is null) miss_b, (p.sku_id is null) miss_p
 from m left join p using (refresh_run_id, sku_id) left join d using (refresh_run_id, sku_id) left join o using (refresh_run_id, sku_id)
 left join c using (refresh_run_id, sku_id) left join i using (refresh_run_id, sku_id) left join b using (refresh_run_id, sku_id))
select run, count(*) n,
 jsonb_build_object(
 'material=rm+pm', count(*) filter (where e_mat<=1e-6),
 'prime.material=material', count(*) filter (where e_mat_xfer<=1e-6),
 'prime=material+DL+IMC', count(*) filter (where e_prime<=1e-6),
 'prime.DL=DL snapshot', count(*) filter (where e_dl_xfer<=1e-6),
 'DL=mfgDL+packingDL', count(*) filter (where e_dl_split<=1e-6),
 'DL split null', count(*) filter (where dl_split_null),
 'cop.prime=prime', count(*) filter (where e_prime_xfer<=1e-6),
 'COP=prime+PO+QC+stores', count(*) filter (where e_cop<=1e-6),
 'cop.OH=overhead snapshot', count(*) filter (where e_oh_xfer<=1e-6),
 'ilc.cop=cop', count(*) filter (where e_cop_xfer<=1e-6),
 'ILC=COP+admin+finadmin', count(*) filter (where e_ilc<=1e-6),
 'ILC=displayed atomic (no IMC)', count(*) filter (where e_ilc_atomic_displayed<=1e-6),
 'ILC=atomic incl IMC', count(*) filter (where e_ilc_atomic_full<=1e-6),
 'ILC displayed atomic diff >=0.01', count(*) filter (where e_ilc_atomic_displayed>=0.01),
 'bridge.ILC=ILC', count(*) filter (where e_ilc_xfer<=1e-6),
 'pricing_cost=ILC+national mkt', count(*) filter (where e_pc<=1e-6),
 'pricing_cost_ik=ILC+mkt_ik', count(*) filter (where e_pc_ik<=1e-6),
 'pricing_cost_ok=ILC+mkt_ok', count(*) filter (where e_pc_ok<=1e-6),
 'ik_margin=mrp_ik-pc_ik', count(*) filter (where e_m_ik<=1e-6),
 'ok_margin=mrp_ok-pc_ok', count(*) filter (where e_m_ok<=1e-6),
 'ik_margin=mrp_ik-pc_national', count(*) filter (where e_m_ik_national<=1e-6),
 'missing', jsonb_build_object('prime',count(*) filter (where miss_p),'dl',count(*) filter (where miss_d),'oh',count(*) filter (where miss_o),'cop',count(*) filter (where miss_c),'ilc',count(*) filter (where miss_i),'bridge',count(*) filter (where miss_b)),
 'fail_lists', jsonb_build_object(
   'prime', jsonb_agg(sku_id order by sku_id) filter (where e_prime>1e-6),
   'dl_split', jsonb_agg(sku_id order by sku_id) filter (where e_dl_split>1e-6),
   'cop', jsonb_agg(sku_id order by sku_id) filter (where e_cop>1e-6),
   'ilc', jsonb_agg(sku_id order by sku_id) filter (where e_ilc>1e-6),
   'ilc_displayed_atomic', jsonb_agg(sku_id order by sku_id) filter (where e_ilc_atomic_displayed>1e-6),
   'ilc_displayed_atomic_ge_0_01', jsonb_agg(sku_id order by sku_id) filter (where e_ilc_atomic_displayed>=0.01),
   'pc_ik', jsonb_agg(sku_id order by sku_id) filter (where e_pc_ik>1e-6),
   'm_ik', jsonb_agg(sku_id order by sku_id) filter (where e_m_ik>1e-6))
 ) checks
from x group by run order by run
