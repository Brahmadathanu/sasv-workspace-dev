// Generates the R1 coverage matrix (Markdown) from the committed manifest plus a LIVE Chromium audit of the six pages.
// Usage: node scripts/costing-preview/build-coverage-matrix.mjs > matrix.md
import { createRequire } from "node:module";
import { createReadOnlyLoopbackServer } from "./read-only-loopback-server.mjs";
import { auditAll } from "./audit-lens-coverage.mjs";
import { COVERAGE } from "./coverage-manifest.mjs";

const { chromium } = createRequire(import.meta.url)("playwright");
const server = await createReadOnlyLoopbackServer();
const base = "http://127.0.0.1:" + server.address().port;
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const desktop = await auditAll({ base, browser, flags: [], width: 1280 });
const navOnly = await auditAll({ base, browser, flags: ["COSTING_NAV_GROUPS_V1"], width: 1280 });
const mobile = await auditAll({ base, browser, flags: [], width: 390 });
await browser.close();
await new Promise((r) => server.close(r));
const find = (rows, c) => rows.find((r) => r.module === c.module && r.id === c.id);
const rendered = (r) => !r ? "?" : r.failureBanner ? "message: " + r.failureBanner.slice(0, 48) : r.dataRows ? r.dataRows + " data row(s)" : "selection prompt / no rows";
const mock = { POPULATED: "MOCK TESTED (populated)", UNSUPPORTED: "NOT TESTED (UNSUPPORTED offline)", SELECTION_REQUIRED: "NOT TESTED (selection needs detail fixture)", RESTRICTED: "RESTRICTED (correct for view-only)" };
const line = ["| Module / lens | Read dependency (observed + contract) | Contract evidence | Safe fixture? | Rendered 1280px | 390px | Nav-only | Mock-test status | Real-data status | Blocker / proposed resolution |", "|---|---|---|---|---|---|---|---|---|---|"];
for (const c of COVERAGE) {
  const d = find(desktop, c), n = find(navOnly, c), m = find(mobile, c);
  line.push("| " + [c.module.replace(/-/g, " ") + " / **" + c.label + "**", c.deps.map((x) => "`" + x + "`").join("<br>"), c.evidence + (c.caveat ? " — *" + c.caveat + "*" : ""),
    c.status === "POPULATED" ? "Yes" : "No", rendered(d), m.dataRows || m.syntheticTextCount ? "ok, no overflow" : rendered(m), n?.hiddenInNav ? "hidden (" + n.hiddenInNav + ")" : "same", mock[c.status], c.realData,
    c.blocker ?? (c.status === "POPULATED" ? "Real-data render needs the authenticated read route (R3)" : "")].join(" | ") + " |");
}
const counts = COVERAGE.reduce((a, c) => ((a[c.status] = (a[c.status] ?? 0) + 1), a), {});
console.log("<!-- generated by scripts/costing-preview/build-coverage-matrix.mjs; status counts " + JSON.stringify(counts) + " -->");
console.log(line.join("\n"));
