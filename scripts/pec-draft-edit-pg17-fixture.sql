CREATE ROLE authenticated NOLOGIN;
CREATE ROLE anon NOLOGIN;
CREATE ROLE service_role NOLOGIN;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT nullif(current_setting('test.user_id',true),'')::uuid $$;
GRANT USAGE ON SCHEMA auth TO authenticated,anon,service_role;
GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated,anon,service_role;
CREATE FUNCTION public.require_permission(p_module text,p_action text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
BEGIN
 IF p_module <> 'module:procurement-execution-console' OR p_action <> 't'
 OR current_setting('test.can_edit',true) IS DISTINCT FROM 'true' THEN
 RAISE EXCEPTION 'PEC edit permission denied';
 END IF;
END $$;
CREATE TABLE public.proc_indent_header(
 indent_id bigint PRIMARY KEY,indent_number text NOT NULL UNIQUE,status text NOT NULL,
 indent_date date NOT NULL,approved_date date,approved_at timestamptz,
 issued_date date,material_class_id bigint,source_pr_id bigint,
 updated_at timestamptz NOT NULL DEFAULT now(),updated_by uuid,
 notes text,
 CONSTRAINT header_status CHECK(status IN('draft','approved','issued','closed','cancelled'))
);
CREATE TABLE public.proc_indent_line(
 indent_line_id bigint PRIMARY KEY,indent_id bigint NOT NULL REFERENCES public.proc_indent_header(indent_id),
 material_class_id bigint NOT NULL,stock_item_id bigint NOT NULL,uom_id bigint NOT NULL,
 requested_qty numeric NOT NULL,manual_reason text,updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(indent_id,material_class_id,stock_item_id,uom_id)
);
CREATE TABLE public.proc_pr_to_indent_map(indent_id bigint,pr_id bigint);
CREATE TABLE public.proc_pr_indent_line_map(indent_id bigint,indent_line_id bigint,pr_line_id bigint);
CREATE TABLE public.proc_indent_line_sourcing_decision(indent_line_id bigint,selected_vendor_id bigint);
CREATE TABLE public.proc_allocation_fixture(indent_line_id bigint,allocated_qty numeric);
CREATE VIEW public.v_proc_indent_line_balance AS
 SELECT l.indent_line_id,coalesce(sum(a.allocated_qty),0)::numeric allocated_qty
 FROM public.proc_indent_line l LEFT JOIN public.proc_allocation_fixture a USING(indent_line_id)
 GROUP BY l.indent_line_id;
CREATE VIEW public.v_proc_indent_fifo_allocation AS SELECT * FROM public.proc_allocation_fixture;
CREATE TABLE public.inv_item_fixture(stock_item_id bigint,subcategory_code text);
CREATE VIEW public.v_inv_stock_item_with_class AS SELECT * FROM public.inv_item_fixture;
CREATE TABLE public.proc_lifecycle_audit(
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_type text NOT NULL,entity_type text NOT NULL,entity_id bigint,
 parent_entity_type text,parent_entity_id bigint, actor_user_id uuid,actor_role text,
 reason text,before_state jsonb,after_state jsonb,context jsonb NOT NULL DEFAULT '{}',
 transaction_id bigint NOT NULL DEFAULT txid_current()
);
CREATE FUNCTION public.proc_lifecycle_audit_write_internal(
 p_event_type text,p_entity_type text,p_entity_id bigint,
 p_parent_entity_type text DEFAULT NULL,p_parent_entity_id bigint DEFAULT NULL,
 p_reason text DEFAULT NULL,p_before_state jsonb DEFAULT NULL,
 p_after_state jsonb DEFAULT NULL,p_context jsonb DEFAULT '{}'
) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,auth AS $$
DECLARE v_id bigint;
BEGIN
 INSERT INTO public.proc_lifecycle_audit(event_type,entity_type,entity_id,parent_entity_type,
 parent_entity_id,actor_user_id,actor_role,reason,before_state,after_state,context)
 VALUES(p_event_type,p_entity_type,p_entity_id,p_parent_entity_type,p_parent_entity_id,
 auth.uid(),current_user,p_reason,p_before_state,p_after_state,p_context)
 RETURNING event_id INTO v_id;
 RETURN v_id;
END $$;
CREATE FUNCTION public.proc_fixture_header_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM public.proc_lifecycle_audit_write_internal(
 'INDENT_UPDATED','indent',NEW.indent_id,NULL,NULL,NULL,to_jsonb(OLD),to_jsonb(NEW),'{}');
 RETURN NEW;
END $$;
CREATE FUNCTION public.proc_fixture_line_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM public.proc_lifecycle_audit_write_internal(
 'INDENT_LINE_CHANGED','indent_line',NEW.indent_line_id,'indent',NEW.indent_id,NULL,to_jsonb(OLD),to_jsonb(NEW),'{}');
 RETURN NEW;
END $$;
