const lf = (t) => String(t).replace(/\r\n/g, "\n");
export function readTb2ViewSql(rootDir = root) {
  const t = lf(fs.readFileSync(path.join(rootDir, TB2_MIGRATION), "utf8"));
  const a = t.indexOf(VIEW_HEAD), b = t.indexOf(NEXT_VIEW_HEAD);
  if (a < 0 || b < a || t.indexOf(VIEW_HEAD, a + 1) >= 0) throw new Error("TB2 view definition not found exactly once");
  return t.slice(a, b).trim(); // "create or replace view ... ;"
}

// [exact old text (regex built from fixed text; whitespace runs allowed), new text]
const SUBQ = (agg, alias) => new RegExp(`\\(\\s*SELECT ${agg}\\s+FROM costing\\.sku_scheme_viability_snapshot s\\s+WHERE \\(s\\.scheme_id = sm\\.id\\)\\) AS ${alias}`);
export const SUBSTITUTIONS = Object.freeze([
  [SUBQ("count\\(\\*\\) AS count", "viability_snapshot_count"), "viab.vs_snapshot_count AS viability_snapshot_count"],
  [SUBQ("count\\(DISTINCT s\\.period_start\\) AS count", "viability_snapshot_period_count"), "viab.vs_period_count AS viability_snapshot_period_count"],
  [SUBQ("max\\(s\\.period_start\\) AS max", "latest_viability_snapshot_period"), "viab.vs_latest_period AS latest_viability_snapshot_period"],
  [/ {3}FROM costing\.scheme_master sm\n\) q\n/, "   FROM costing.scheme_master sm\n   LEFT JOIN LATERAL (\n     SELECT count(*) AS vs_snapshot_count,\n            count(DISTINCT s.period_start) AS vs_period_count,\n            max(s.period_start) AS vs_latest_period\n       FROM costing.sku_scheme_viability_snapshot s\n      WHERE s.scheme_id = sm.id\n   ) viab ON true\n) q\n"],
]);

export function buildCandidateViewSql(tb2 = readTb2ViewSql()) {
  let t = tb2 + "\n";
  for (const [re, to] of SUBSTITUTIONS) {
    const hits = t.match(new RegExp(re.source, "g")) ?? [];
    if (hits.length !== 1) throw new Error(`substitution ${re} matched ${hits.length} times (must be exactly 1)`);
    t = t.replace(re, () => to);
  }
  return t.trimEnd();
}
/** The view body without the CREATE header and trailing semicolon: usable inline as a CTE (runs with the caller's privileges, like a security_invoker view). */
export const viewBody = (viewSql) => viewSql.slice(viewSql.indexOf(VIEW_HEAD) + VIEW_HEAD.length).trim().replace(/;$/, "");

const HEADER = (title) => `-- ${title}\n-- CANDIDATE ONLY - NOT APPLIED. Generated by scripts/scheme-master-perf-candidate/build.mjs from ${TB2_MIGRATION}. Do not edit by hand; re-run the generator.\n-- Issue #211 (B): v_costing_scheme_master_register intermittently exceeds the statement timeout (57014) on the Pricing Policy Manager Scheme Master workspace.\n`;

export function candidateSql() {
  const body = buildCandidateViewSql();
  return `${HEADER("Scheme Master register: one per-scheme LATERAL aggregate for the three viability statistics")}--
-- WHAT CHANGES: the three correlated subqueries over costing.sku_scheme_viability_snapshot (count(*), count(DISTINCT period_start), max(period_start)) become ONE
--   LEFT JOIN LATERAL aggregate per scheme row. The 31 other columns, all names, order, types, NULL handling, security_invoker=true and the outer
--   "where (select public.fn_costing_view_allowed())" gate are textually unchanged. No ORDER BY is added (the client orders by scheme_name).
-- WHY THIS SHAPE: measured live, SELECT-only (issue #211, 8 Nov 2026): baseline warm 231.433 ms (206,906 shared hits), this shape 124.916 ms (102,883 hits),
--   all 7 scheme rows identical on the 3 changed columns; the global GROUP BY alternative was slower (2,941.849 ms, temp sort) and is NOT used.
-- NOT CHANGED: grants (CREATE OR REPLACE VIEW keeps ACL and reloptions), the table, indexes, RLS, any RPC, any client code, any flag.
-- APPLY ONLY after the owner's approval gates in README.md (all-column parity, grant/permission parity, plan timing, backup of the TB2 definition).
-- ROLLBACK: scheme_master_register_rollback_tb2.sql (restores the TB2 text byte for byte).
--
-- Precondition: fail closed if the live view is not exactly the expected pre-change shape (drift would mean this candidate was reviewed against different SQL).
do $pre$
declare v_def text; v_opts text[]; v_cols int;
begin
  select pg_get_viewdef('${VIEW}'::regclass, true), c.reloptions into v_def, v_opts from pg_class c where c.oid = '${VIEW}'::regclass;
  select count(*) into v_cols from pg_attribute where attrelid = '${VIEW}'::regclass and attnum > 0 and not attisdropped;
  if v_cols <> ${COLUMNS.length} then raise exception 'scheme-master candidate precondition: expected ${COLUMNS.length} columns, found %', v_cols; end if;
  if v_opts is null or not (v_opts @> array['security_invoker=true']) then raise exception 'scheme-master candidate precondition: security_invoker=true missing'; end if;
  if v_def !~ 'fn_costing_view_allowed' then raise exception 'scheme-master candidate precondition: permission gate missing'; end if;
  if (select count(*) from regexp_matches(v_def, 'sku_scheme_viability_snapshot', 'g')) <> 3 then raise exception 'scheme-master candidate precondition: expected exactly 3 viability snapshot references (pre-change shape)'; end if;
end
$pre$;

${body}
`;
}

