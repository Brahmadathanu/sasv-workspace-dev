-- TEST-ONLY deterministic barrier. A statement-level trigger on the first
-- UPDATE of proc_indent_line made by application 'sess_A' waits on advisory
-- lock 777, which the controller holds. No sleeps are used for ordering.
CREATE FUNCTION public.fx_pause() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('application_name') = 'sess_A' THEN
    PERFORM pg_advisory_lock(777); PERFORM pg_advisory_unlock(777);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER fx_pause_trg BEFORE UPDATE ON public.proc_indent_line
  FOR EACH STATEMENT EXECUTE FUNCTION public.fx_pause();

-- Edit a draft PR line through the REAL PR writer, pause, then activate the PR.
CREATE FUNCTION public.fx_pr_edit_pause_activate(p_line bigint, p_delta numeric) RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_pr bigint;
BEGIN
  SELECT pr_id INTO v_pr FROM public.proc_pr_line WHERE pr_line_id = p_line;
  PERFORM public.proc_pr_set_manual_delta_pec_internal(p_line, p_delta, 'edit');
  PERFORM pg_advisory_lock(777); PERFORM pg_advisory_unlock(777);
  UPDATE public.proc_pr_header SET status='active' WHERE pr_id=v_pr;
END $$;

CREATE FUNCTION public.fx_state_md5(p_indent bigint) RETURNS text LANGUAGE sql AS $$
  SELECT md5(coalesce((SELECT string_agg(concat_ws('|',indent_line_id,stock_item_id,requested_qty,manual_reason),';' ORDER BY indent_line_id)
                       FROM public.proc_indent_line WHERE indent_id=p_indent),'')
          || '#' || coalesce((SELECT string_agg(concat_ws('|',indent_line_id,pr_line_id),';' ORDER BY indent_line_id)
                       FROM public.proc_pr_indent_line_map WHERE indent_id=p_indent),'')
          || '#' || coalesce((SELECT string_agg(concat_ws('|',map_id,is_active,note),';' ORDER BY map_id)
                       FROM public.proc_pr_to_indent_map WHERE indent_id=p_indent),'')
          || '#' || coalesce((SELECT concat_ws('|',status,source_pr_id) FROM public.proc_indent_header WHERE indent_id=p_indent),''))
$$;

