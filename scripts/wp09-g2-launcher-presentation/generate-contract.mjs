// Generates public/shared/js/launcher-presentation-contract.js from the ACCEPTED G1 mapping and the committed live snapshot.
// Presentation data only: module_key -> [live section, approved subgroup, family|""]. No permission, route or registry data.
// Usage: node scripts/wp09-g2-launcher-presentation/generate-contract.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MAPPING } from "../wp09-g1-launcher-audit/module-mapping.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const snap = JSON.parse(fs.readFileSync(path.join(root, "docs/master-data-costing/WP09_G1_EVIDENCE/live-registry-snapshot-2026-11-15.json"), "utf8"));
const live = new Map();
for (const r of snap.registry.filter((r) => r.nav_enabled && r.client_key === "electron")) live.set(r.module_key, r.section_key);

const rows = MAPPING.map((m) => [m.key, m.optA.section, m.optA.sub, m.optC || ""]).sort((a, b) => a[0].localeCompare(b[0]));
for (const [key, section] of rows) if (live.get(key) !== section) throw new Error(`mapping section differs from live snapshot for ${key}`);
if (rows.length !== live.size || rows.some(([k]) => !live.has(k))) throw new Error("mapping keys differ from the 79 live Electron keys");

const body = rows.map(([k, s, sub, fam]) => `  ${JSON.stringify(k)}: Object.freeze([${JSON.stringify(s)}, ${JSON.stringify(sub)}, ${JSON.stringify(fam)}]),`).join("\n");
const out = `// GENERATED by scripts/wp09-g2-launcher-presentation/generate-contract.mjs — do not edit by hand.
// WP09 G2 presentation contract (79 registered keys; sections = current live sections; see WP09_G1_EVIDENCE/module-group-mapping.csv).
// module_key -> [sectionKey, subgroup, family ("" = flat tile)]. PRESENTATION ONLY: it grants nothing, adds no registry module and
// no permission target. Keys absent from this table (future registrations) render in the fallback subgroup and never disappear.
export const LAUNCHER_PRESENTATION_CONTRACT = Object.freeze({
${body}
});
`;
const target = path.join(root, "public/shared/js/launcher-presentation-contract.js");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== out) { console.error("contract is stale"); process.exit(1); }
  console.log(`contract up to date (${rows.length} keys)`);
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote ${rows.length} keys`);
}
