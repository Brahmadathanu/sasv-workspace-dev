-- 3. Current column list of a run-scoped table (attnum order = whole-row order)
create or replace function costing.fn_run_fingerprint_current_columns(p_table text)
returns text[] language sql stable set search_path to 'costing','public','pg_temp' as $f$
  select array_agg(a.attname::text order by a.attnum)
  from pg_attribute a where a.attrelid = format('costing.%I', p_table)::regclass and a.attnum > 0 and not a.attisdropped
$f$;

-- 4. Hash one table for one run over an explicit column list. Same text as the old whole-row hash when cols = all columns.
create or replace function costing.fn_run_fingerprint_table_hash(p_table text, p_refresh_run_id bigint, p_cols text[])
returns jsonb language plpgsql stable set search_path to 'costing','public','pg_temp' as $f$
declare v_row text; v_n bigint; v_h text; v_missing text[];
begin
  select array_agg(c) into v_missing from unnest(p_cols) c where not (c = any (costing.fn_run_fingerprint_current_columns(p_table)));
  if v_missing is not null then
    raise exception 'W5_FINGERPRINT_COLUMNS_MISSING: costing.% no longer has column(s) %', p_table, v_missing;
  end if;
  v_row := 'row(' || (select string_agg(format('x.%I', c), ',' order by o) from unnest(p_cols) with ordinality u(c, o)) || ')::text';
  execute format('select count(*), md5(coalesce(string_agg(%s, %L order by %s), %L)) from costing.%I x where x.refresh_run_id = $1',
                 v_row, '|', v_row, '', p_table)
    into v_n, v_h using p_refresh_run_id;
  return jsonb_build_object('rows', v_n, 'md5', v_h, 'cols', to_jsonb(p_cols));
end $f$;

-- 5. Capture: same tables, same md5 as before, plus the recorded column list
create or replace function costing.fn_compute_run_fingerprint(p_refresh_run_id bigint)
returns jsonb language plpgsql stable set search_path to 'costing','public','pg_temp' as $f$
declare t text; v_e jsonb; v jsonb := '{}'::jsonb;
begin
  for t in select * from costing.fn_costing_run_scoped_tables() loop
    v_e := costing.fn_run_fingerprint_table_hash(t, p_refresh_run_id, costing.fn_run_fingerprint_current_columns(t));
    if (v_e->>'rows')::bigint > 0 then v := v || jsonb_build_object(t, v_e); end if;
  end loop;
  return v;
end $f$;

-- 6. Verify against the latest capture using that capture's recorded columns (old captures: all current columns, as before)
create or replace function costing.fn_verify_run_fingerprint(p_refresh_run_id bigint)
returns table(table_name text, captured jsonb, current_value jsonb, matches boolean)
language plpgsql stable set search_path to 'costing','public','pg_temp' as $f$
declare v_cap jsonb; k text; v_cols text[]; v_cur jsonb;
begin
  select f.fingerprint into v_cap from costing.costing_run_fingerprint f where f.refresh_run_id = p_refresh_run_id
   order by f.captured_at desc, f.id desc limit 1;
  if v_cap is null then return; end if;
  for k in select key from jsonb_object_keys(v_cap) key union select s from costing.fn_costing_run_scoped_tables() s order by 1 loop
    begin
      if v_cap ? k and v_cap->k ? 'cols' then
        select array_agg(c order by o) into v_cols from jsonb_array_elements_text(v_cap->k->'cols') with ordinality u(c, o);
      else
        v_cols := costing.fn_run_fingerprint_current_columns(k);   -- legacy capture: whole row, exactly as before
      end if;
      v_cur := costing.fn_run_fingerprint_table_hash(k, p_refresh_run_id, v_cols);
    exception when others then
      v_cur := jsonb_build_object('error', sqlerrm);
    end;
    continue when not (v_cap ? k) and (v_cur->>'rows')::bigint = 0;   -- scoped table with no rows for this run and not captured
    table_name := k; captured := v_cap->k; current_value := v_cur;
    matches := v_cap ? k and v_cur ? 'md5'
               and (v_cap->k->>'rows') is not distinct from (v_cur->>'rows') and (v_cap->k->>'md5') is not distinct from (v_cur->>'md5');
    return next;
  end loop;
end $f$;

-- 7. Governed re-baseline: records a column-fixed capture only if every table equals the reference capture
create or replace function costing.rpc_rebaseline_run_fingerprint(
  p_refresh_run_id bigint, p_reference_fingerprint_id bigint, p_excluded_columns jsonb,
  p_rebaselined_by text, p_reason text, p_approval_reference text)
returns bigint language plpgsql security definer set search_path to 'costing','public','pg_temp' as $f$
declare v_ref costing.costing_run_fingerprint%rowtype; t text; v_cols text[]; v_ex text[]; v_e jsonb; v_new jsonb := '{}'::jsonb;
        v_bad jsonb := '[]'::jsonb; v_ev jsonb := '[]'::jsonb; v_latest costing.costing_run_fingerprint%rowtype; v_fp bigint; v_nn bigint; c text;
begin
  if coalesce(length(btrim(p_rebaselined_by)),0) = 0 or coalesce(length(btrim(p_reason)),0) < 10 or coalesce(length(btrim(p_approval_reference)),0) = 0 then
    raise exception 'W5_REBASELINE_EVIDENCE_REQUIRED'; end if;
  select * into v_ref from costing.costing_run_fingerprint where id = p_reference_fingerprint_id;
  if not found or v_ref.refresh_run_id <> p_refresh_run_id then
    raise exception 'W5_REBASELINE_BAD_REFERENCE: fingerprint % is not a capture of run %', p_reference_fingerprint_id, p_refresh_run_id; end if;
  perform pg_advisory_xact_lock(hashtextextended('w5-rebaseline:' || p_refresh_run_id, 0));
  -- every table that now holds rows for the run must be in the reference
  for t in select s from costing.fn_costing_run_scoped_tables() s loop
    if not (v_ref.fingerprint ? t) and (costing.fn_run_fingerprint_table_hash(t, p_refresh_run_id, costing.fn_run_fingerprint_current_columns(t))->>'rows')::bigint > 0 then
      v_bad := v_bad || jsonb_build_object('table', t, 'problem', 'rows exist but table not in reference capture'); end if;
  end loop;
  for t in select key from jsonb_object_keys(v_ref.fingerprint) key order by 1 loop
    select coalesce(array_agg(x), '{}') into v_ex from jsonb_array_elements_text(coalesce(p_excluded_columns->t, '[]'::jsonb)) x;
    v_cols := costing.fn_run_fingerprint_current_columns(t);
    if exists (select 1 from unnest(v_ex) x where not (x = any (v_cols))) then
      v_bad := v_bad || jsonb_build_object('table', t, 'problem', 'excluded column does not exist'); continue; end if;
    -- an excluded column must hold no value for this run (it did not exist when the reference was captured)
    foreach c in array v_ex loop
      execute format('select count(*) from costing.%I where refresh_run_id = $1 and %I is not null', t, c) into v_nn using p_refresh_run_id;
      if v_nn > 0 then v_bad := v_bad || jsonb_build_object('table', t, 'problem', format('excluded column %s has %s non-null values', c, v_nn)); end if;
    end loop;
    select array_agg(x order by o) into v_cols from unnest(v_cols) with ordinality u(x, o) where not (x = any (v_ex));
    v_e := costing.fn_run_fingerprint_table_hash(t, p_refresh_run_id, v_cols);
    if (v_e->>'rows') is distinct from (v_ref.fingerprint->t->>'rows') or (v_e->>'md5') is distinct from (v_ref.fingerprint->t->>'md5') then
      v_bad := v_bad || jsonb_build_object('table', t, 'problem', 'values differ from reference', 'reference', v_ref.fingerprint->t, 'current', v_e - 'cols');
    end if;
    v_new := v_new || jsonb_build_object(t, v_e);
    v_ev := v_ev || jsonb_build_object('table', t, 'rows', v_e->'rows', 'md5', v_e->'md5', 'reference_md5', v_ref.fingerprint->t->'md5',
                                        'excluded', to_jsonb(v_ex), 'identical', (v_e->>'md5') = (v_ref.fingerprint->t->>'md5'));
  end loop;
  if jsonb_array_length(v_bad) > 0 then
    raise exception 'W5_REBASELINE_REFUSED: run % does not equal reference capture %: %', p_refresh_run_id, p_reference_fingerprint_id, v_bad;
  end if;
  -- idempotent: the latest capture is already this exact re-baseline
  select * into v_latest from costing.costing_run_fingerprint where refresh_run_id = p_refresh_run_id order by captured_at desc, id desc limit 1;
  if v_latest.purpose = 'REBASELINE' and v_latest.fingerprint = v_new then return v_latest.id; end if;
  insert into costing.costing_run_fingerprint(refresh_run_id, purpose, captured_by, fingerprint)
  values (p_refresh_run_id, 'REBASELINE', p_rebaselined_by, v_new) returning id into v_fp;
  insert into costing.costing_run_fingerprint_rebaseline(refresh_run_id, fingerprint_id, reference_fingerprint_id, excluded_columns, reason, approval_reference, rebaselined_by, evidence)
  values (p_refresh_run_id, v_fp, p_reference_fingerprint_id, coalesce(p_excluded_columns, '{}'::jsonb), p_reason, p_approval_reference, p_rebaselined_by,
          jsonb_build_object('tables', v_ev, 'all_identical', true));
  return v_fp;
end $f$;
