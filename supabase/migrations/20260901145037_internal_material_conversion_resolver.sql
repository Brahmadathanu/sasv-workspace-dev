create table if not exists costing.sku_internal_material_conversion_snapshot (
  id bigint generated by default as identity primary key,
  period_start date not null,
  valuation_date date not null,
  refresh_run_id bigint not null references costing.costing_refresh_run(id),
  sku_id bigint not null,
  product_id bigint not null,
  product_name text,
  pack_size numeric,
  pack_uom text,
  sku_base_qty_per_unit numeric,
  internal_source_line_count bigint not null default 0,
  internal_conversion_cost_per_product_base_uom numeric,
  internal_conversion_cost_per_sku numeric,
  conversion_status text not null,
  conversion_reason_code text,
  conversion_note text,
  evidence_json jsonb not null default '[]'::jsonb,
  refreshed_at timestamptz not null default clock_timestamp(),
  unique(refresh_run_id,sku_id),
  check(conversion_status in ('READY','REVIEW_REQUIRED','BLOCKED'))
);

create index if not exists ix_sku_internal_material_conversion_snapshot_product
  on costing.sku_internal_material_conversion_snapshot(refresh_run_id,product_id);

create or replace function costing.fn_resolve_product_internal_conversion_burden(
  p_source_product_id bigint,
  p_refresh_run_id bigint,
  p_visited_source_product_ids bigint[] default array[]::bigint[]
)
returns table(
  source_product_id bigint,
  source_product_name text,
  source_product_base_uom text,
  direct_manufacturing_labour_per_base numeric,
  direct_production_overhead_per_base numeric,
  direct_qc_overhead_per_base numeric,
  direct_rm_stores_overhead_per_base numeric,
  child_internal_conversion_per_base numeric,
  total_conversion_burden_per_base numeric,
  conversion_status text,
  reason_code text,
  evidence_json jsonb
)
language plpgsql
stable security definer
set search_path to 'costing','public','pg_temp'
as $$
declare
  v_run costing.costing_refresh_run%rowtype;
  v_name text;
  v_product_status text;
  v_qc_status text;
  v_base_uom text;
  v_base_qty numeric;
  v_dl numeric;
  v_poh numeric;
  v_qc numeric;
  v_stores numeric;
  v_child_total numeric := 0;
  v_direct numeric;
  v_blocked boolean := false;
  v_review boolean := false;
  v_rec record;
  v_child record;
  v_evidence jsonb := '[]'::jsonb;
begin
  if p_source_product_id is null or p_refresh_run_id is null then
    raise exception 'source_product_id and refresh_run_id are required';
  end if;

  select * into v_run from costing.costing_refresh_run r where r.id=p_refresh_run_id;
  if not found then raise exception 'Costing refresh run % not found',p_refresh_run_id; end if;

  if p_source_product_id = any(coalesce(p_visited_source_product_ids,array[]::bigint[])) then
    return query select p_source_product_id,null::text,null::text,null::numeric,null::numeric,null::numeric,null::numeric,
      null::numeric,null::numeric,'BLOCKED'::text,'INTERNAL_CONVERSION_CYCLE'::text,
      jsonb_build_array(jsonb_build_object('visited',p_visited_source_product_ids,'source_product_id',p_source_product_id));
    return;
  end if;

  select p.item,p.status into v_name,v_product_status from public.products p where p.id=p_source_product_id;
  if v_product_status is distinct from 'Active' then
    return query select p_source_product_id,v_name,null::text,null::numeric,null::numeric,null::numeric,null::numeric,
      null::numeric,null::numeric,'BLOCKED'::text,'INTERNAL_SOURCE_PRODUCT_INACTIVE'::text,
      jsonb_build_array(jsonb_build_object('product_status',v_product_status));
    return;
  end if;

  select max(b.product_base_uom),max(b.monthly_product_allocation_base_qty)
  into v_base_uom,v_base_qty
  from costing.sku_sales_allocation_basis_snapshot b
  where b.refresh_run_id=p_refresh_run_id and b.product_id=p_source_product_id;

  if v_base_uom is null or v_base_qty is null or v_base_qty<=0 then
    return query select p_source_product_id,v_name,v_base_uom,null::numeric,null::numeric,null::numeric,null::numeric,
      null::numeric,null::numeric,'BLOCKED'::text,'MISSING_SOURCE_PRODUCT_ABSORPTION_BASIS'::text,'[]'::jsonb;
    return;
  end if;

  select sum(d.manufacturing_direct_labour_allocation)/v_base_qty
  into v_dl
  from costing.sku_direct_labour_allocation_snapshot d
  where d.refresh_run_id=p_refresh_run_id and d.product_id=p_source_product_id;
  if v_dl is null then v_blocked:=true; end if;
  if exists(select 1 from costing.sku_direct_labour_allocation_snapshot d where d.refresh_run_id=p_refresh_run_id and d.product_id=p_source_product_id and d.direct_labour_allocation_status='BLOCKED') then v_blocked:=true; end if;
  if exists(select 1 from costing.sku_direct_labour_allocation_snapshot d where d.refresh_run_id=p_refresh_run_id and d.product_id=p_source_product_id and d.direct_labour_allocation_status='REVIEW_REQUIRED') then v_review:=true; end if;

  select max(p.production_overhead_cost_per_base_uom)
  into v_poh
  from costing.sku_production_overhead_allocation_snapshot p
  where p.refresh_run_id=p_refresh_run_id and p.product_id=p_source_product_id;
  if v_poh is null then v_blocked:=true; end if;
  if exists(select 1 from costing.sku_production_overhead_allocation_snapshot p where p.refresh_run_id=p_refresh_run_id and p.product_id=p_source_product_id and p.allocation_status='BLOCKED') then v_blocked:=true; end if;
  if exists(select 1 from costing.sku_production_overhead_allocation_snapshot p where p.refresh_run_id=p_refresh_run_id and p.product_id=p_source_product_id and p.allocation_status='REVIEW_REQUIRED') then v_review:=true; end if;

  select q.qc_cost_per_product_base_uom,q.allocation_status into v_qc,v_qc_status
  from costing.product_qc_allocation_snapshot q
  where q.refresh_run_id=p_refresh_run_id and q.product_id=p_source_product_id;
  if v_qc is null or v_qc_status='BLOCKED' then v_blocked:=true; elsif v_qc_status='REVIEW_REQUIRED' then v_review:=true; end if;

  select sum(a.monthly_sku_allocation_amount * case when w.unified_workload_units>0 then w.rm_workload_units/w.unified_workload_units else 0 end)/v_base_qty
  into v_stores
  from costing.sku_materials_stores_allocation_snapshot a
  join costing.sku_materials_stores_workload_snapshot w
    on w.refresh_run_id=a.refresh_run_id and w.sku_id=a.sku_id
  where a.refresh_run_id=p_refresh_run_id and a.product_id=p_source_product_id;
  if v_stores is null then v_blocked:=true; end if;
  if exists(select 1 from costing.sku_materials_stores_allocation_snapshot a where a.refresh_run_id=p_refresh_run_id and a.product_id=p_source_product_id and a.allocation_status='BLOCKED') then v_blocked:=true; end if;
  if exists(select 1 from costing.sku_materials_stores_allocation_snapshot a where a.refresh_run_id=p_refresh_run_id and a.product_id=p_source_product_id and a.allocation_status='REVIEW_REQUIRED') then v_review:=true; end if;

  v_direct:=case when v_blocked then null else coalesce(v_dl,0)+coalesce(v_poh,0)+coalesce(v_qc,0)+coalesce(v_stores,0) end;
  v_evidence:=v_evidence||jsonb_build_array(jsonb_build_object(
    'direct_manufacturing_labour_per_base',v_dl,'direct_production_overhead_per_base',v_poh,
    'direct_qc_overhead_per_base',v_qc,'direct_rm_stores_overhead_per_base',v_stores,'product_base_qty',v_base_qty));

  for v_rec in
    select l.qty_purchase_form_per_base_unit,il.source_product_id as child_source_product_id,
           l.purchase_stock_item_id,l.purchase_stock_item_name
    from costing.product_rm_material_cost_line_snapshot l
    join costing.internal_material_source_lineage il
      on il.consume_stock_item_id=l.purchase_stock_item_id
     and il.status='APPROVED'
     and il.effective_from<=v_run.valuation_date
     and (il.effective_to is null or il.effective_to>=v_run.valuation_date)
    where l.refresh_run_id=p_refresh_run_id and l.product_id=p_source_product_id
      and coalesce(l.is_optional,false)=false
  loop
    select * into v_child
    from costing.fn_resolve_product_internal_conversion_burden(
      v_rec.child_source_product_id,p_refresh_run_id,
      coalesce(p_visited_source_product_ids,array[]::bigint[])||p_source_product_id
    );

    if v_rec.qty_purchase_form_per_base_unit is null or v_child.total_conversion_burden_per_base is null or v_child.conversion_status='BLOCKED' then
      v_blocked:=true;
    else
      v_child_total:=v_child_total + v_rec.qty_purchase_form_per_base_unit*v_child.total_conversion_burden_per_base;
      if v_child.conversion_status='REVIEW_REQUIRED' then v_review:=true; end if;
    end if;

    v_evidence:=v_evidence||jsonb_build_array(jsonb_build_object(
      'child_stock_item_id',v_rec.purchase_stock_item_id,'child_source_product_id',v_rec.child_source_product_id,
      'qty_per_source_base',v_rec.qty_purchase_form_per_base_unit,'child_conversion_per_base',v_child.total_conversion_burden_per_base,
      'child_status',v_child.conversion_status));
  end loop;

  if v_blocked then
    return query select p_source_product_id,v_name,v_base_uom,v_dl,v_poh,v_qc,v_stores,v_child_total,null::numeric,
      'BLOCKED'::text,'INTERNAL_SOURCE_CONVERSION_BLOCKED'::text,v_evidence;
  elsif v_review then
    return query select p_source_product_id,v_name,v_base_uom,v_dl,v_poh,v_qc,v_stores,v_child_total,
      coalesce(v_direct,0)+v_child_total,'REVIEW_REQUIRED'::text,'INTERNAL_SOURCE_CONVERSION_REVIEW_REQUIRED'::text,v_evidence;
  else
    return query select p_source_product_id,v_name,v_base_uom,v_dl,v_poh,v_qc,v_stores,v_child_total,
      coalesce(v_direct,0)+v_child_total,'READY'::text,'READY_INTERNAL_SOURCE_CONVERSION'::text,v_evidence;
  end if;
end;
$$;