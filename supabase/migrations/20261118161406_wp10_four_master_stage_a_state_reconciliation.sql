-- WP10 four-master STAGE A — state-aware, fail-closed reconciliation migration.
-- Tables: public.categories, public.sub_categories, public.product_groups, public.sub_groups (judged as ONE atomic unit).
--
-- Production project qhmoqtxpeasamtlxaoak ALREADY runs the reviewed Stage A policies (applied directly 18 Nov 2026, postflight 58/58).
-- This file exists so migration history and fresh/older databases converge on the same security state WITHOUT replaying Stage A.
--
--   STATE A  all four tables carry exactly their ORIGINAL single identity-only FOR ALL policy, and every dependency check passes
--            -> install the reviewed Stage A policies (SELECT identity-only; INSERT/UPDATE(USING+CHECK)/DELETE require
--               app_has_permission(key,'view') AND app_has_permission(key,'edit')), then re-verify the exact end state.
--   STATE B  all four tables already carry exactly the approved Stage A policies and every dependency check passes
--            -> verified NO-OP: no DDL, no GRANT/REVOKE, no data change (policy OIDs are untouched).
--   STATE C  anything else (mixed / partial / altered / foreign policies, wrong key, edit-without-view, extra grants, Stage B applied,
--            RLS off or forced, missing or drifted helper/RPC) -> RAISE; the transaction rolls back and nothing changes.
--
-- "Exact" is judged against reference policies generated BY THE SAME SERVER from the same templates into a transient ON COMMIT DROP temp
-- table, so the comparison is independent of the PostgreSQL version's expression pretty-printing. No persistent object is created, no new
-- privilege granted, no function/RPC/trigger touched, no business data read or written. Stage B (REVOKE) is NOT part of this file and is
-- refused as an unexpected state. Never replace this with the original 02_stage_a_apply.sql on a database that may already be hardened.
begin;

set local lock_timeout = '2s';
set local statement_timeout = '30s';

-- ---- transient helpers (pg_temp; removed before COMMIT) -------------------------------------------------------------------------------
create temp table wp10_stage_a_ref (id integer) on commit drop;
alter table wp10_stage_a_ref enable row level security;

-- the ONE template for the Stage A write predicate (used to create the reference AND the real policies)
create function pg_temp.wp10_pred(p_key text) returns text language sql immutable as $f$
  select format('((select public.app_has_permission(%L, ''view'')) and (select public.app_has_permission(%L, ''edit'')))', p_key, p_key)
$f$;

create function pg_temp.wp10_policy_ddl(p_rel text, p_tbl text, p_key text) returns text[] language sql immutable as $f$
  select array[
    format('create policy %I on %s for select to authenticated using ((select auth.uid()) is not null)', p_tbl || '_authenticated_read', p_rel),
    format('create policy %I on %s for insert to authenticated with check (%s)', p_tbl || '_authenticated_insert', p_rel, pg_temp.wp10_pred(p_key)),
    format('create policy %I on %s for update to authenticated using (%s) with check (%s)', p_tbl || '_authenticated_update', p_rel, pg_temp.wp10_pred(p_key), pg_temp.wp10_pred(p_key)),
    format('create policy %I on %s for delete to authenticated using (%s)', p_tbl || '_authenticated_delete', p_rel, pg_temp.wp10_pred(p_key))]
$f$;

-- classify one table: 'ORIGINAL' | 'HARDENED' | 'OTHER'
create function pg_temp.wp10_table_state(p_tbl text) returns text language plpgsql as $f$
declare
  v_rel regclass := to_regclass('public.' || p_tbl);
  v_auth oid := (select oid from pg_roles where rolname = 'authenticated');
  v_n int; v_cmd text; v_suffix text; v_ref record; v_pol record;
begin
  if v_rel is null or v_auth is null then return 'OTHER'; end if;
  select count(*) into v_n from pg_policy where polrelid = v_rel;
  if v_n = 1 then
    select * into v_ref from pg_policy where polrelid = 'pg_temp.wp10_stage_a_ref'::regclass and polname = 'orig_' || p_tbl;
    select * into v_pol from pg_policy where polrelid = v_rel and polname = p_tbl || '_authenticated_crud';
    if v_pol.oid is not null and v_pol.polcmd = '*' and v_pol.polpermissive and v_pol.polroles = array[v_auth]::oid[]
       and pg_get_expr(v_pol.polqual, v_pol.polrelid) is not distinct from pg_get_expr(v_ref.polqual, v_ref.polrelid)
       and pg_get_expr(v_pol.polwithcheck, v_pol.polrelid) is not distinct from pg_get_expr(v_ref.polwithcheck, v_ref.polrelid) then
      return 'ORIGINAL';
    end if;
    return 'OTHER';
  end if;
  if v_n <> 4 then return 'OTHER'; end if;
  for v_cmd, v_suffix in select * from (values ('r','read'), ('a','insert'), ('w','update'), ('d','delete')) x loop
    select * into v_ref from pg_policy where polrelid = 'pg_temp.wp10_stage_a_ref'::regclass and polname = 'ref_' || p_tbl || '_' || v_suffix;
    select * into v_pol from pg_policy where polrelid = v_rel and polname = p_tbl || '_authenticated_' || v_suffix;
    if v_pol.oid is null or v_pol.polcmd <> v_cmd::"char" or not v_pol.polpermissive or v_pol.polroles <> array[v_auth]::oid[]
       or pg_get_expr(v_pol.polqual, v_pol.polrelid) is distinct from pg_get_expr(v_ref.polqual, v_ref.polrelid)
       or pg_get_expr(v_pol.polwithcheck, v_pol.polrelid) is distinct from pg_get_expr(v_ref.polwithcheck, v_ref.polrelid) then
      return 'OTHER';
    end if;
  end loop;
  return 'HARDENED';
end $f$;

-- ---- main -----------------------------------------------------------------------------------------------------------------------------
do $wp10$
declare
  v_tables constant text[] := array['categories','sub_categories','product_groups','sub_groups'];
  v_keys   constant text[] := array['module:manage-categories','module:manage-subcategories','module:manage-product-groups','module:manage-subgroups'];
  v_rpc_stems constant text[] := array['category','subcategory','product_group','subgroup'];
  v_problems text[] := array[]::text[];
  v_states text[] := array[]::text[];
  v_i int; v_t text; v_k text; v_rel regclass; v_sig text; v_op text; v_rpc text; v_state text; v_n int; v_ddl text; v_row record;
begin
  -- 0a. prerequisites that must exist before anything else can be evaluated (controlled refusal instead of a raw SQL error)
  foreach v_t in array v_tables loop
    if to_regclass('public.' || v_t) is null then v_problems := v_problems || ('missing table public.' || v_t); end if;
  end loop;
  foreach v_sig in array array['public.app_has_permission(text,text)', 'public.app_has_permission_core(uuid,text,text)', 'public.require_permission(text,boolean)'] loop
    if to_regprocedure(v_sig) is null then v_problems := v_problems || ('missing helper ' || v_sig); end if;
  end loop;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then v_problems := v_problems || 'missing role authenticated'; end if;
  if array_length(v_problems, 1) is not null then
    raise exception 'WP10 Stage A reconciliation REFUSED (state C / unexpected). Nothing was changed. Problems: %', array_to_string(v_problems, ' | ');
  end if;
  -- serialise against concurrent DDL on the four tables (does not block reads or writes)
  lock table public.categories, public.sub_categories, public.product_groups, public.sub_groups in share update exclusive mode;

  -- 0b. reference policies, generated by this server from the same templates
  for v_i in 1..4 loop
    v_t := v_tables[v_i]; v_k := v_keys[v_i];
    execute format('create policy %I on pg_temp.wp10_stage_a_ref for all to authenticated using ((select auth.uid()) is not null) with check ((select auth.uid()) is not null)', 'orig_' || v_t);
    foreach v_ddl in array pg_temp.wp10_policy_ddl('pg_temp.wp10_stage_a_ref', v_t, v_k) loop
      execute replace(v_ddl, 'create policy ' || quote_ident(v_t || '_authenticated_'), 'create policy ' || quote_ident('ref_' || v_t || '_'));
    end loop;
  end loop;

  -- 1. dependency / invariant checks common to every acceptable state
  foreach v_sig in array array['public.app_has_permission(text,text)', 'public.app_has_permission_core(uuid,text,text)', 'public.require_permission(text,boolean)'] loop
    if not has_function_privilege('authenticated', to_regprocedure(v_sig), 'EXECUTE') then v_problems := v_problems || ('authenticated lacks EXECUTE on ' || v_sig); end if;
    if exists (select 1 from pg_roles where rolname = 'anon') and has_function_privilege('anon', to_regprocedure(v_sig), 'EXECUTE') then v_problems := v_problems || ('anon can EXECUTE ' || v_sig); end if;
  end loop;

  for v_i in 1..4 loop
    v_t := v_tables[v_i]; v_k := v_keys[v_i]; v_rel := to_regclass('public.' || v_t);
    if v_rel is null then v_problems := v_problems || ('missing table public.' || v_t); continue; end if;
    select * into v_row from pg_class where oid = v_rel;
    if not v_row.relrowsecurity then v_problems := v_problems || (v_t || ': RLS not enabled'); end if;
    if v_row.relforcerowsecurity then v_problems := v_problems || (v_t || ': RLS is FORCED (would block the table-owner governed RPCs)'); end if;
    -- grants: exactly the pre-Stage-B set; no PUBLIC/anon; authenticated exactly SELECT,INSERT,UPDATE,DELETE; no grantee outside owner/postgres/service_role/authenticated
    for v_row in select a.grantee, a.privilege_type from aclexplode(coalesce((select relacl from pg_class where oid = v_rel), acldefault('r', (select relowner from pg_class where oid = v_rel)))) a loop
      if v_row.grantee = 0 then v_problems := v_problems || (v_t || ': PUBLIC grant ' || v_row.privilege_type);
      elsif v_row.grantee not in ((select relowner from pg_class where oid = v_rel)) and pg_get_userbyid(v_row.grantee) not in ('postgres', 'service_role', 'authenticated') then
        v_problems := v_problems || (v_t || ': unexpected grantee ' || pg_get_userbyid(v_row.grantee));
      end if;
    end loop;
    select count(*) into v_n from aclexplode((select relacl from pg_class where oid = v_rel)) a where pg_get_userbyid(a.grantee) = 'authenticated' and a.privilege_type in ('SELECT','INSERT','UPDATE','DELETE');
    if v_n <> 4 then v_problems := v_problems || (v_t || ': authenticated does not hold exactly SELECT/INSERT/UPDATE/DELETE (Stage B applied or grants altered); found ' || v_n || ' of the 4'); end if;
    select count(*) into v_n from aclexplode((select relacl from pg_class where oid = v_rel)) a where pg_get_userbyid(a.grantee) = 'authenticated' and a.privilege_type not in ('SELECT','INSERT','UPDATE','DELETE');
    if v_n <> 0 then v_problems := v_problems || (v_t || ': authenticated holds extra table privileges'); end if;
    select count(*) into v_n from aclexplode((select relacl from pg_class where oid = v_rel)) a where exists (select 1 from pg_roles r where r.oid = a.grantee and r.rolname = 'anon');
    if v_n <> 0 then v_problems := v_problems || (v_t || ': anon holds table privileges'); end if;

    -- the twelve governed RPCs for this table
    foreach v_op in array array['create','rename','delete'] loop
      v_rpc := 'rpc_wp10_' || v_op || '_' || v_rpc_stems[v_i];
      select count(*) into v_n from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = v_rpc;
      if v_n <> 1 then v_problems := v_problems || ('RPC ' || v_rpc || ': expected exactly one, found ' || v_n); continue; end if;
      select p.* into v_row from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = v_rpc;
      if not v_row.prosecdef then v_problems := v_problems || ('RPC ' || v_rpc || ' is not SECURITY DEFINER'); end if;
      if not (v_row.proowner = (select relowner from pg_class where oid = v_rel) or coalesce((select rolbypassrls or rolsuper from pg_roles where oid = v_row.proowner), false)) then
        v_problems := v_problems || ('RPC ' || v_rpc || ': owner neither table owner nor BYPASSRLS');
      end if;
      if v_row.prosrc !~* ('require_permission\(\s*''' || v_k || '''\s*,\s*true\s*\)') then v_problems := v_problems || ('RPC ' || v_rpc || ': body lacks require_permission(''' || v_k || ''', true)'); end if;
      if not has_function_privilege('authenticated', v_row.oid, 'EXECUTE') then v_problems := v_problems || ('RPC ' || v_rpc || ': authenticated lacks EXECUTE'); end if;
      if exists (select 1 from aclexplode(coalesce(v_row.proacl, acldefault('f', v_row.proowner))) a where a.grantee = 0) then v_problems := v_problems || ('RPC ' || v_rpc || ': PUBLIC EXECUTE'); end if;
    end loop;
  end loop;

  -- SECURITY INVOKER functions that write the four tables would be subject to the new policies
  for v_row in select p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                where n.nspname not in ('pg_catalog','information_schema') and p.prokind in ('f','p') and not p.prosecdef
                  and p.prosrc ~* '(insert\s+into|update|delete\s+from|merge\s+into)\s+(only\s+)?("?public"?\.)?"?(categories|sub_categories|product_groups|sub_groups)"?\M' loop
    v_problems := v_problems || ('SECURITY INVOKER function writes a four-master table: ' || v_row.proname);
  end loop;

  -- 2. classify the four tables as one unit
  for v_i in 1..4 loop v_states := v_states || pg_temp.wp10_table_state(v_tables[v_i]); end loop;
  v_state := case when v_states = array['ORIGINAL','ORIGINAL','ORIGINAL','ORIGINAL'] then 'A'
                  when v_states = array['HARDENED','HARDENED','HARDENED','HARDENED'] then 'B' else 'C' end;
  if v_state = 'C' then v_problems := v_problems || ('policy state not uniform/exact: ' || array_to_string(v_tables, ',') || ' => ' || array_to_string(v_states, ',')); end if;

  if array_length(v_problems, 1) is not null then
    raise exception 'WP10 Stage A reconciliation REFUSED (state C / unexpected). Nothing was changed. Problems: %', array_to_string(v_problems, ' | ');
  end if;

  -- 3a. STATE B: verified no-op
  if v_state = 'B' then
    raise notice 'WP10 Stage A reconciliation: STATE B - approved Stage A policies already present and verified; no changes made.';
    return;
  end if;

  -- 3b. STATE A: install the reviewed Stage A policies (all four tables, one transaction), then re-verify the exact end state
  for v_i in 1..4 loop
    v_t := v_tables[v_i]; v_k := v_keys[v_i];
    execute format('drop policy %I on public.%I', v_t || '_authenticated_crud', v_t);
    foreach v_ddl in array pg_temp.wp10_policy_ddl('public.' || quote_ident(v_t), v_t, v_k) loop execute v_ddl; end loop;
  end loop;
  v_states := array[]::text[];
  for v_i in 1..4 loop v_states := v_states || pg_temp.wp10_table_state(v_tables[v_i]); end loop;
  if v_states <> array['HARDENED','HARDENED','HARDENED','HARDENED'] then
    raise exception 'WP10 Stage A reconciliation post-check failed (%); rolling back.', array_to_string(v_states, ',');
  end if;
  raise notice 'WP10 Stage A reconciliation: STATE A - original identity-only policies replaced by the reviewed Stage A policies.';
end $wp10$;

drop function pg_temp.wp10_table_state(text);
drop function pg_temp.wp10_policy_ddl(text, text, text);
drop function pg_temp.wp10_pred(text);

commit;
