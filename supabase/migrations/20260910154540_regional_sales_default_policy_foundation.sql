  cancellation_reason text,
  cancellation_approval_reference text,
  constraint regional_sales_default_dates_chk
    check ((effective_to is null) or (effective_to >= effective_from)),
  constraint regional_sales_default_region_chk
    check (region_code = any (array['IK'::text, 'OK'::text])),
  constraint regional_sales_default_scenario_chk
    check (
      scenario_code = any (
        array[
          'NO_ELIGIBLE_REGIONAL_HISTORY'::text,
          'NO_POSITIVE_REGIONAL_HISTORY'::text
        ]
      )
    ),
