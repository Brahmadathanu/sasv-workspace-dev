CREATE OR REPLACE FUNCTION public.rpc_set_regional_sales_allocation_default_policy(p_scenario_code text, p_region_code text, p_default_sales_units numeric, p_effective_from date, p_reason text, p_approval_reference text DEFAULT NULL::text)
 RETURNS TABLE(policy_id bigint, scenario_code text, region_code text, default_sales_units numeric, effective_from date, effective_to date, status text, previous_policy_id bigint, created_at timestamp with time zone, created_by uuid)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'costing', 'pg_temp'
AS $function$
declare
    v_actor uuid; v_scenario text; v_region text; v_reason text; v_ref text;
    v_previous costing.regional_sales_allocation_default_policy%rowtype;
    v_saved costing.regional_sales_allocation_default_policy%rowtype;
begin
    perform public.require_permission('module:pricing-policy-manager',true);
    v_actor:=auth.uid();
    if v_actor is null then raise exception 'Authenticated user context is required'; end if;
    v_scenario:=upper(btrim(coalesce(p_scenario_code,'')));
    v_region:=upper(btrim(coalesce(p_region_code,'')));
    if v_scenario not in ('NO_ELIGIBLE_REGIONAL_HISTORY','NO_POSITIVE_REGIONAL_HISTORY') then raise exception 'Invalid regional allocation policy scenario.'; end if;
    if v_region not in ('IK','OK') then raise exception 'Region must be IK or OK.'; end if;
    if p_default_sales_units is null or p_default_sales_units<=0 then raise exception 'Default sales units must be greater than zero.'; end if;
    if p_effective_from is null then raise exception 'Effective-from date is required.'; end if;
    v_reason:=nullif(btrim(coalesce(p_reason,'')),'');
    if v_reason is null then raise exception 'Reason is required.'; end if;
    v_ref:=nullif(btrim(coalesce(p_approval_reference,'')),'');
    perform pg_advisory_xact_lock(hashtextextended('PPM_REGIONAL_SALES_ALLOCATION_DEFAULT:'||v_scenario||':'||v_region,0));
    select * into v_previous from costing.regional_sales_allocation_default_policy p
      where p.scenario_code=v_scenario and p.region_code=v_region and p.status='APPROVED' and p.effective_to is null
      order by p.effective_from desc,p.id desc limit 1 for update;
    if found then
      if p_effective_from<=v_previous.effective_from then raise exception 'New policy effective date must be later than the current open policy effective date %.',v_previous.effective_from; end if;
      update costing.regional_sales_allocation_default_policy set effective_to=p_effective_from-1,status='CLOSED',closed_at=clock_timestamp(),closed_by=v_actor where id=v_previous.id;
    end if;
    insert into costing.regional_sales_allocation_default_policy(scenario_code,region_code,default_sales_units,effective_from,status,reason,approval_reference,previous_policy_id,created_at,created_by)
    values(v_scenario,v_region,p_default_sales_units,p_effective_from,'APPROVED',v_reason,v_ref,v_previous.id,clock_timestamp(),v_actor)
    returning * into v_saved;
    return query select v_saved.id,v_saved.scenario_code,v_saved.region_code,v_saved.default_sales_units,v_saved.effective_from,v_saved.effective_to,v_saved.status,v_saved.previous_policy_id,v_saved.created_at,v_saved.created_by;
end;
$function$;

