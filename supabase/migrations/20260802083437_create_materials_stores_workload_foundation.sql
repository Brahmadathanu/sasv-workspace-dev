        end,
        case
            when rm.required_rm_line_count = 0 and pm.required_pm_line_count = 0 then 'BLOCKED_NO_RM_OR_PM_STANDARD_EVIDENCE'
            when rm.rm_evidence_status = 'BLOCKED' then rm.rm_evidence_reason
            when pm.pm_evidence_status = 'BLOCKED' then pm.pm_evidence_reason
            when b.monthly_driver_status = 'BLOCKED' then 'BLOCKED_MONTHLY_ALLOCATION_BASIS'
            when rm.rm_evidence_status = 'REVIEW_REQUIRED' then rm.rm_evidence_reason
            when pm.pm_evidence_status = 'REVIEW_REQUIRED' then pm.pm_evidence_reason
            when b.monthly_driver_status = 'REVIEW_REQUIRED' then 'REVIEW_MONTHLY_ALLOCATION_BASIS'
            else 'READY'
        end,
        case
            when rm.required_rm_line_count = 0 and pm.required_pm_line_count = 0 then 'No governed RM or PM standard workload evidence exists for this SKU.'
            when rm.rm_evidence_status = 'BLOCKED' then 'Materials / Stores workload is blocked by the Product RM standard-evidence condition.'
            when pm.pm_evidence_status = 'BLOCKED' then 'Materials / Stores workload is blocked by the SKU PM standard-evidence condition.'
            when b.monthly_driver_status = 'BLOCKED' then 'Materials / Stores workload is blocked because the governed monthly allocation basis is blocked.'
            when rm.rm_evidence_status = 'REVIEW_REQUIRED' then 'Materials / Stores workload uses zero RM pending governed classification and requires review.'
            when pm.pm_evidence_status = 'REVIEW_REQUIRED' then 'Materials / Stores workload uses zero PM pending governed classification and requires review.'
            when b.monthly_driver_status = 'REVIEW_REQUIRED' then 'Materials / Stores workload is calculated using a governed assumed or default monthly quantity and requires review.'
            else 'Materials / Stores workload is ready.'
        end
    from costing.sku_sales_allocation_basis_snapshot b
    join costing.product_rm_stores_workload_snapshot rm
      on rm.refresh_run_id = b.refresh_run_id
     and rm.product_id = b.product_id
    join costing.sku_pm_stores_workload_snapshot pm
      on pm.refresh_run_id = b.refresh_run_id
     and pm.sku_id = b.sku_id
    where b.period_start = v_period_start
      and b.valuation_date = p_valuation_date
      and b.refresh_run_id = p_refresh_run_id;

    update costing.sku_materials_stores_workload_snapshot s
    set company_eligible_workload_units = x.company_eligible_workload_units,
        workload_share = case
            when s.allocation_status = 'BLOCKED' then null
            when x.company_eligible_workload_units <= 0 then null
            else s.unified_workload_units / x.company_eligible_workload_units
        end
    from (
        select refresh_run_id, sum(unified_workload_units) filter (where allocation_status <> 'BLOCKED') as company_eligible_workload_units
        from costing.sku_materials_stores_workload_snapshot
        where refresh_run_id = p_refresh_run_id
        group by refresh_run_id
    ) x
    where s.refresh_run_id = x.refresh_run_id;

    if exists (
        select 1
        from costing.sku_materials_stores_workload_snapshot s
        where s.refresh_run_id = p_refresh_run_id
          and s.allocation_status <> 'BLOCKED'
          and (s.unified_workload_units is null or s.unified_workload_units <= 0 or s.workload_share is null)
    ) then
        raise exception 'Materials / Stores workload contains a nonblocked row with missing or nonpositive workload for refresh run %', p_refresh_run_id;
    end if;

    return query
    select
        v_period_start,
        (select count(*) from costing.product_rm_stores_workload_snapshot where refresh_run_id = p_refresh_run_id),
        (select count(*) from costing.sku_pm_stores_workload_snapshot where refresh_run_id = p_refresh_run_id),
        count(*)::bigint,
        count(*) filter (where s.allocation_status = 'BLOCKED')::bigint,
        count(*) filter (where s.allocation_status = 'REVIEW_REQUIRED')::bigint,
        count(*) filter (where s.allocation_status = 'READY')::bigint
    from costing.sku_materials_stores_workload_snapshot s
    where s.refresh_run_id = p_refresh_run_id;
end;
$$;

