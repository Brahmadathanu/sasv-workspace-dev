create or replace function public.rpc_get_regional_marketing_action_queue(
    p_period_start date default null,
    p_region_code text default null,
    p_action_code text default null,
    p_q text default null,
    p_limit integer default 100,
    p_offset integer default 0
)
returns table (row_data jsonb, total_count bigint)
language plpgsql
security definer
set search_path = public, costing, pg_temp
as $function$
declare
    v_period_start date := case when p_period_start is null then null else date_trunc('month',p_period_start)::date end;
    v_region_code text := nullif(upper(btrim(coalesce(p_region_code,''))), '');
    v_action_code text := nullif(upper(btrim(coalesce(p_action_code,''))), '');
    v_q text := nullif(btrim(coalesce(p_q,'')), '');
begin
    perform public.require_permission('module:pricing-policy-manager', false);

    if v_region_code is not null and v_region_code not in ('IK','OK') then
        raise exception 'Region must be IK or OK.';
    end if;

    return query
    with filtered as (
        select q.*
        from costing.v_regional_marketing_action_queue_current q
        where (v_period_start is null or q.period_start = v_period_start)
          and (v_region_code is null or q.region_code = v_region_code)
          and (v_action_code is null or q.action_code = v_action_code)
          and (
              v_q is null
              or q.product_name ilike '%' || v_q || '%'
              or q.sku_id::text ilike '%' || v_q || '%'
              or q.product_id::text ilike '%' || v_q || '%'
              or q.action_code ilike '%' || v_q || '%'
              or q.recommended_action ilike '%' || v_q || '%'
          )
    ), counted as (
        select count(*)::bigint as total_count from filtered
    ), page as (
        select f.*
        from filtered f
        order by f.action_priority, f.region_code, f.product_name, f.pack_size nulls last, f.sku_id
        limit greatest(coalesce(p_limit,100),1)
        offset greatest(coalesce(p_offset,0),0)
    )
    select to_jsonb(page.*), counted.total_count
    from page cross join counted;
end;
$function$;

