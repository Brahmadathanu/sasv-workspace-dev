        raise exception 'Costing refresh run % does not exist', p_refresh_run_id;
    end if;

    if v_run.period_start is distinct from v_period_start
       or v_run.valuation_date is distinct from p_valuation_date
       or v_run.valuation_context_source is distinct from 'CAPTURED_AT_REQUEST' then
        raise exception 'Regional Marketing action-queue context does not match refresh run %', p_refresh_run_id;
    end if;

    if v_run.overall_status not in ('QUEUED','RUNNING','FAILED') then
        raise exception 'Regional Marketing action queue cannot be refreshed for terminal run % with status %', p_refresh_run_id, v_run.overall_status;
    end if;

    if not exists (
        select 1
        from costing.sku_regional_marketing_allocation_basis_snapshot b
        where b.period_start = v_period_start
          and b.valuation_date = p_valuation_date
