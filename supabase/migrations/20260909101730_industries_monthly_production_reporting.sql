create or replace view public.v_industries_product_canonical_rate
with (security_invoker = true) as
with x as (
  select
    product_id,
    qty_in_uom_base_unit as uom_base,
    qty_in_uom_base,
    book_line_value,
    case when qty_in_uom_base <> 0 then book_line_value / qty_in_uom_base end as line_rate
  from public.v_tally_fg_transfer_normalized_valued
  where transfer_date >= date '2025-04-01'
    and transfer_date < date '2026-09-01'
    and product_id is not null
    and qty_in_uom_base is not null
    and qty_in_uom_base <> 0
    and book_line_value is not null
), a as (
  select
    product_id,
    uom_base,
    sum(qty_in_uom_base) as transfer_qty_basis,
    sum(book_line_value) as transfer_value_basis,
    sum(book_line_value) / nullif(sum(qty_in_uom_base),0) as canonical_rate,
    min(line_rate) as min_line_rate,
    max(line_rate) as max_line_rate,
    count(*) as transfer_line_count
  from x
  group by product_id, uom_base
)
select
  a.*,
  case when canonical_rate <> 0 then (max_line_rate-min_line_rate)/abs(canonical_rate)*100 end as observed_rate_span_pct,
  case
    when transfer_line_count < 2 then 'LIMITED_EVIDENCE'
    when canonical_rate = 0 then 'REVIEW'
    when (max_line_rate-min_line_rate)/nullif(abs(canonical_rate),0) > 0.50 then 'REVIEW_HIGH_VARIATION'
    else 'OK'
  end as rate_status
from a;

create or replace view public.v_industries_monthly_production_group
with (security_invoker = true) as
select
  b.month_start,
  d.group_name as product_group,
  b.uom_base,
  sum(b.quantity_base) as aggregated_quantity,
  sum(b.quantity_base * r.canonical_rate) as aggregated_value,
  count(distinct b.product_id) as product_count,
  count(*) filter (where r.canonical_rate is null) as missing_rate_rows,
  count(*) filter (where r.rate_status like 'REVIEW%') as rate_review_rows
from public.industries_monthly_production_basis b
left join public.v_product_details d on d.product_id=b.product_id
left join public.v_industries_product_canonical_rate r on r.product_id=b.product_id and r.uom_base=b.uom_base
where b.month_start >= date '2022-04-01' and b.month_start < date '2026-09-01'
group by b.month_start, d.group_name, b.uom_base;
