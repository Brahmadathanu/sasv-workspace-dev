returns trigger language plpgsql security definer set search_path=public,auth as $$
declare v_event text; v_reason text;
begin
 if tg_op='INSERT' then
   perform public.proc_lifecycle_audit_write_internal('PR_CREATED','pr',new.pr_id,null,null,new.notes,null,to_jsonb(new),jsonb_build_object('table',tg_table_name));
   return new;
 elsif tg_op='DELETE' then
   perform public.proc_lifecycle_audit_write_internal('PR_DELETED','pr',old.pr_id,null,null,old.notes,to_jsonb(old),null,jsonb_build_object('table',tg_table_name));
   return old;
 end if;
 if new.status is distinct from old.status then
   v_event := case lower(new.status)
     when 'active' then 'PR_ACTIVATED' when 'closed' then 'PR_CLOSED' when 'cancelled' then 'PR_CANCELLED'
     when 'draft' then 'PR_SET_DRAFT' else 'PR_STATUS_CHANGED' end;
 else
   if (to_jsonb(new)-array['updated_at','updated_by']) = (to_jsonb(old)-array['updated_at','updated_by']) then return new; end if;
   v_event := 'PR_UPDATED';
 end if;
 v_reason := case when new.notes is distinct from old.notes then new.notes else null end;
 perform public.proc_lifecycle_audit_write_internal(v_event,'pr',new.pr_id,null,null,v_reason,to_jsonb(old),to_jsonb(new),jsonb_build_object('table',tg_table_name,'old_status',old.status,'new_status',new.status));
 return new;
end; $$;
