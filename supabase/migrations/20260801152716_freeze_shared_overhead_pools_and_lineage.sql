declare
    v_oid oid;
    v_def text;
    v_old text;
    v_new text;
begin
    select p.oid, pg_get_functiondef(p.oid)
    into v_oid, v_def
    from pg_proc p
    join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='costing'
      and p.proname='rpc_refresh_manufacturing_cop_chain'
      and pg_get_function_identity_arguments(p.oid)='p_period_start date, p_valuation_date date, p_refresh_run_id bigint';

    v_old := E'        perform *\r\n        from costing.rpc_refresh_sku_overhead_allocation_snapshot(\r\n            v_period_start,\r\n            p_valuation_date,\r\n            p_refresh_run_id\r\n        );';

    v_new := E'        perform *\r\n        from costing.rpc_refresh_cost_pool_monthly_snapshot(\r\n            v_period_start,\r\n            p_valuation_date,\r\n            p_refresh_run_id\r\n        );\r\n\r\n\r\n        perform *\r\n        from costing.rpc_refresh_sku_overhead_allocation_snapshot(\r\n            v_period_start,\r\n            p_valuation_date,\r\n            p_refresh_run_id\r\n        );';

    if position(v_old in v_def)=0 then
        raise exception 'Stage 03 overhead anchor not found';
    end if;

    execute replace(v_def, v_old, v_new);
end;
