    expense_provision_amount numeric not null default 0,
    manual_provision_amount numeric not null default 0,
    total_pool_amount numeric not null,
    source_basis text not null default 'MONTHLY_COMBINED_POOL',
    pool_status text not null,
    pool_note text not null,
