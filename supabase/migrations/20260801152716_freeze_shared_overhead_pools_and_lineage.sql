    constraint cost_pool_monthly_snapshot_uq unique (refresh_run_id, allocation_pool),
    constraint cost_pool_monthly_snapshot_pool_chk check (
        allocation_pool in (
            'PRODUCTION_OVERHEAD',
            'QUALITY_CONTROL_OVERHEAD',
            'MATERIALS_STORES_OVERHEAD'
        )
    ),
    constraint cost_pool_monthly_snapshot_status_chk check (
        pool_status in ('READY','REVIEW_REQUIRED','BLOCKED')
    ),
    constraint cost_pool_monthly_snapshot_total_chk check (
        total_pool_amount = staff_pool_amount + expense_provision_amount + manual_provision_amount
    )
