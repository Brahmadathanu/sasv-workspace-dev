create or replace function regulatory.trg_validate_stability_study_qc_contract()
returns trigger
language plpgsql
set search_path to 'regulatory','public','pg_temp'
as $$
declare
  v_code text;
  v_domain text;
begin
  select domain_code,code into v_domain,v_code
  from regulatory.controlled_term
  where id=new.testing_protocol_term_id;

  if v_domain is distinct from 'QC_PROTOCOL' then
    raise exception using errcode='23514', message='stability_study testing protocol must belong to QC_PROTOCOL';
  end if;

  if v_code='OTHER' then
    if nullif(btrim(coalesce(new.other_testing_protocol_text,'')),'') is null then
      raise exception using errcode='23514', message='Other Testing Protocol text is required when QC protocol is OTHER';
    end if;
  elsif new.other_testing_protocol_text is not null then
    raise exception using errcode='23514', message='Other Testing Protocol text must be null unless QC protocol is OTHER';
  end if;

  return new;
end
$$;

