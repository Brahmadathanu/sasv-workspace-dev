end$$;

create or replace function public.rpc_approve_product_route_family_assignment(
  p_assignment_id bigint,
  p_approval_reference text,
  p_effective_from date default null
) returns jsonb
language plpgsql security definer
set search_path='public','costing'
as $$
begin
  perform public.require_permission('module:production-route-manager',true);
  if nullif(btrim(p_approval_reference),'') is null or upper(btrim(p_approval_reference)) in ('-','—','NA','N/A') then
    raise exception 'A meaningful approval reference is required';
  end if;
  update costing.production_route_family_product_map
  set effective_from=coalesce(p_effective_from,effective_from),status='APPROVED',
      approval_reference=btrim(p_approval_reference),approved_by=auth.uid(),approved_at=now(),updated_at=now()
  where id=p_assignment_id and status in ('DRAFT','IN_REVIEW');
  if not found then raise exception 'Product Route Family assignment is not approvable'; end if;
  return jsonb_build_object('assignment_id',p_assignment_id,'status','APPROVED');
end$$;

create or replace function public.rpc_inactivate_product_route_family_assignment(
  p_assignment_id bigint,
  p_effective_to date
) returns jsonb
language plpgsql security definer
set search_path='public','costing'
as $$
begin
  perform public.require_permission('module:production-route-manager',true);
  update costing.production_route_family_product_map
  set status='INACTIVE',effective_to=p_effective_to,updated_at=now()
