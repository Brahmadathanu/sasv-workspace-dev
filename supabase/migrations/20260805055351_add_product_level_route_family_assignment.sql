create table if not exists costing.production_route_family_product_map (
  id bigint generated by default as identity primary key,
  route_family_id bigint not null references costing.production_route_family(id) on delete restrict,
  product_id integer not null references public.products(id) on delete restrict,
  status text not null default 'DRAFT' check (status in ('DRAFT','IN_REVIEW','APPROVED','SUPERSEDED','INACTIVE')),
  effective_from date not null,
  effective_to date,
  assignment_basis text not null default 'HISTORICAL_REVIEW' check (assignment_basis in ('MANUAL','HISTORICAL_REVIEW','MIGRATED')),
  assignment_note text,
  approval_reference text,
  approved_by uuid,
  approved_at timestamptz,
  supersedes_assignment_id bigint references costing.production_route_family_product_map(id) on delete restrict,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (effective_to is null or effective_to >= effective_from),
  check (status <> 'APPROVED' or (approval_reference is not null and approved_at is not null))
);

create index if not exists production_route_family_product_map_product_idx
  on costing.production_route_family_product_map(product_id,effective_from,effective_to,status);
create index if not exists production_route_family_product_map_family_idx
  on costing.production_route_family_product_map(route_family_id,status);

create or replace function costing.fn_product_route_family_assignment_guard()
returns trigger
language plpgsql
set search_path='costing','public'
as $$
declare
  v_product_status text;
begin
  if tg_op='DELETE' then
    if old.status='APPROVED' then
      raise exception 'Approved Product Route Family assignment is immutable; inactivate or supersede instead';
    end if;
    return old;
  end if;

  if new.effective_to is not null and new.effective_to < new.effective_from then
    raise exception 'Assignment effective-to cannot precede effective-from';
  end if;

  select upper(coalesce(p.status,'')) into v_product_status
  from public.products p where p.id=new.product_id;
  if v_product_status is distinct from 'ACTIVE' then
    raise exception 'Product % must be ACTIVE for Route Family assignment',new.product_id;
  end if;

  if new.status='APPROVED' then
    if not exists(
      select 1 from costing.production_route_family f
      where f.id=new.route_family_id and f.status='APPROVED'
        and f.effective_from<=new.effective_from
        and (f.effective_to is null or f.effective_to>=new.effective_from)
    ) then
      raise exception 'Route Family % must be approved and effective for assignment',new.route_family_id;
    end if;
    if nullif(btrim(new.approval_reference),'') is null or new.approved_at is null then
      raise exception 'Approved Product assignment requires approval reference and timestamp';
    end if;
    if exists(
      select 1
      from costing.production_route_family_product_map x
      where x.id<>coalesce(new.id,0)
        and x.product_id=new.product_id
        and x.status='APPROVED'
        and daterange(x.effective_from,coalesce(x.effective_to,'infinity'::date),'[]')
            && daterange(new.effective_from,coalesce(new.effective_to,'infinity'::date),'[]')
    ) then
      raise exception 'Product % already has an overlapping approved Route Family assignment',new.product_id;
    end if;
  end if;

  if tg_op='UPDATE' and old.status='APPROVED' then
    if new.status not in ('APPROVED','SUPERSEDED','INACTIVE') then
      raise exception 'Approved Product assignment may only remain approved or become superseded/inactive';
    end if;
    if (to_jsonb(old)-array['status','effective_to','updated_at'])
       is distinct from
       (to_jsonb(new)-array['status','effective_to','updated_at']) then
      raise exception 'Approved Product assignment definition is immutable';
    end if;
  end if;

  return new;
end$$;

drop trigger if exists trg_product_route_family_assignment_guard on costing.production_route_family_product_map;
create trigger trg_product_route_family_assignment_guard
before insert or update or delete on costing.production_route_family_product_map
for each row execute function costing.fn_product_route_family_assignment_guard();

create or replace function costing.fn_resolve_route_family_for_product(p_product_id integer,p_as_of_date date default current_date)
returns bigint
language plpgsql
stable security definer
set search_path='costing','public'
as $$
declare
  v_date date:=coalesce(p_as_of_date,current_date);
  v_product_family bigint;
  v_group_family bigint;
begin
  select m.route_family_id into v_product_family
  from costing.production_route_family_product_map m
  join costing.production_route_family f on f.id=m.route_family_id
  where m.product_id=p_product_id
    and m.status='APPROVED'
    and m.effective_from<=v_date
    and (m.effective_to is null or m.effective_to>=v_date)
    and f.status='APPROVED'
    and f.effective_from<=v_date
    and (f.effective_to is null or f.effective_to>=v_date)
  order by m.effective_from desc,m.id desc
  limit 1;

  select gm.route_family_id into v_group_family
  from public.products p
  join public.sub_groups sg on sg.id=p.sub_group_id
  join costing.production_route_family_product_group_map gm
    on gm.product_group_id=sg.product_group_id
   and gm.status='APPROVED'
   and gm.effective_from<=v_date
   and (gm.effective_to is null or gm.effective_to>=v_date)
  join costing.production_route_family f on f.id=gm.route_family_id
   and f.status='APPROVED'
   and f.effective_from<=v_date
   and (f.effective_to is null or f.effective_to>=v_date)
  where p.id=p_product_id
  order by gm.effective_from desc,gm.id desc
  limit 1;

  if v_product_family is not null and v_group_family is not null and v_product_family<>v_group_family then
    raise exception 'Conflicting Product-level and Product Group Route Family assignments for Product %',p_product_id;
  end if;

  return coalesce(v_product_family,v_group_family);
end$$;

create or replace function costing.fn_validate_product_process_route(p_product_route_id bigint)
returns jsonb
language plpgsql
stable security definer
set search_path='costing','public'
as $$
declare
  v_route costing.product_process_route%rowtype;
  v_errors jsonb:='[]'::jsonb;
  v_family_id bigint;
  v_base_family_id bigint;
  v_batch_product_id integer;
  v_steps integer;
  v_rm integer;
  v_fg integer;
  v_prod integer;
begin
  select * into v_route from costing.product_process_route where id=p_product_route_id;
  if not found then return jsonb_build_object('valid',false,'errors',jsonb_build_array('PRODUCT_ROUTE_NOT_FOUND')); end if;

  v_family_id:=costing.fn_resolve_route_family_for_product(v_route.product_id,coalesce(v_route.effective_from,current_date));
  select route_family_id into v_base_family_id from costing.production_route_family_route where id=v_route.base_route_family_route_id;

  if v_family_id is null then v_errors:=v_errors||jsonb_build_array('NO_APPROVED_ROUTE_FAMILY_ASSIGNMENT');
  elsif v_family_id<>v_base_family_id then v_errors:=v_errors||jsonb_build_array('ROUTE_FAMILY_ASSIGNMENT_MISMATCH'); end if;

  if not exists(select 1 from costing.production_route_family_route where id=v_route.base_route_family_route_id and status='APPROVED') then
    v_errors:=v_errors||jsonb_build_array('BASE_ROUTE_FAMILY_ROUTE_NOT_APPROVED');
  end if;

  select product_id into v_batch_product_id from public.production_batch_size_ref where id=v_route.batch_size_ref_id;
  if v_batch_product_id is distinct from v_route.product_id then v_errors:=v_errors||jsonb_build_array('BATCH_REFERENCE_PRODUCT_MISMATCH'); end if;

  if exists(
    select 1 from costing.product_process_route_override o
    join costing.production_route_family_route_step s on s.id=o.base_step_id
    where o.product_route_id=p_product_route_id and s.family_route_id<>v_route.base_route_family_route_id
  ) then v_errors:=v_errors||jsonb_build_array('OVERRIDE_REFERENCES_FOREIGN_ROUTE_FAMILY_STEP'); end if;

  select count(*),count(*) filter(where route_step_scope='BOUNDARY_RM_ISSUE'),count(*) filter(where route_step_scope='BOUNDARY_FG_TRANSFER'),count(*) filter(where route_step_scope='PRODUCTION_PROCESS')
  into v_steps,v_rm,v_fg,v_prod
  from costing.fn_effective_product_process_route_steps(p_product_route_id);
  if v_steps=0 then v_errors:=v_errors||jsonb_build_array('NO_ROUTE_STEPS'); end if;
  if v_rm<>1 then v_errors:=v_errors||jsonb_build_array('REQUIRES_EXACTLY_ONE_RM_ISSUE_BOUNDARY'); end if;
  if v_fg<>1 then v_errors:=v_errors||jsonb_build_array('REQUIRES_EXACTLY_ONE_FG_TRANSFER_BOUNDARY'); end if;
  if v_prod<1 then v_errors:=v_errors||jsonb_build_array('REQUIRES_PRODUCTION_PROCESS_STEP'); end if;
  if exists(select 1 from costing.fn_effective_product_process_route_steps(p_product_route_id) group by sequence_no having count(*)>1) then
    v_errors:=v_errors||jsonb_build_array('DUPLICATE_EFFECTIVE_SEQUENCE');
  end if;
  if v_route.evidence_status not in ('MANUAL_COMPLETE','HISTORICAL_COMPLETE') then v_errors:=v_errors||jsonb_build_array('INCOMPLETE_ROUTE_EVIDENCE'); end if;
  return jsonb_build_object('valid',jsonb_array_length(v_errors)=0,'errors',v_errors,'step_count',v_steps,'rm_boundary_count',v_rm,'fg_boundary_count',v_fg,'production_step_count',v_prod,'resolved_route_family_id',v_family_id);
end$$;

create or replace function public.rpc_create_product_route_family_assignment_draft(
  p_product_id integer,
  p_route_family_id bigint,
  p_effective_from date default current_date,
  p_assignment_basis text default 'HISTORICAL_REVIEW',
  p_assignment_note text default null
) returns jsonb
language plpgsql security definer
set search_path='public','costing'
as $$
declare v_id bigint;
begin
  perform public.require_permission('module:production-route-manager',true);
  if upper(coalesce(p_assignment_basis,'')) not in ('MANUAL','HISTORICAL_REVIEW','MIGRATED') then
    raise exception 'Invalid assignment basis';
  end if;
  if exists(
    select 1 from costing.production_route_family_product_map
    where product_id=p_product_id and status in ('DRAFT','IN_REVIEW','APPROVED')
      and daterange(effective_from,coalesce(effective_to,'infinity'::date),'[]')
          && daterange(coalesce(p_effective_from,current_date),'infinity'::date,'[]')
  ) then raise exception 'Product already has an active or pending Route Family assignment'; end if;
  insert into costing.production_route_family_product_map(
    route_family_id,product_id,effective_from,assignment_basis,assignment_note,status,created_by
  ) values(
    p_route_family_id,p_product_id,coalesce(p_effective_from,current_date),upper(p_assignment_basis),nullif(btrim(p_assignment_note),''),'DRAFT',auth.uid()
  ) returning id into v_id;
  return jsonb_build_object('assignment_id',v_id,'status','DRAFT');
end$$;

create or replace function public.rpc_submit_product_route_family_assignment_for_review(p_assignment_id bigint)
returns jsonb
language plpgsql security definer
set search_path='public','costing'
as $$
begin
  perform public.require_permission('module:production-route-manager',true);
  update costing.production_route_family_product_map set status='IN_REVIEW',updated_at=now()
  where id=p_assignment_id and status='DRAFT';
