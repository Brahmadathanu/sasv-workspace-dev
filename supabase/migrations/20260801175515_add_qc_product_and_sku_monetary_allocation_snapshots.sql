create table if not exists costing.product_qc_allocation_snapshot (
    id bigint generated by default as identity primary key,
    period_start date not null,
    valuation_date date not null,
    refresh_run_id bigint not null references costing.costing_refresh_run(id),
    product_workload_snapshot_id bigint not null references costing.product_qc_workload_snapshot(id),
    policy_id bigint not null references costing.qc_workload_policy(id),
    quality_control_pool_snapshot_id bigint not null references costing.cost_pool_monthly_snapshot(id),
    product_id bigint not null,
    product_name text,
    product_group_id bigint,
    protocol_category_id bigint,
    base_spec_profile_id bigint,
    workload_units numeric,
    company_resolved_workload_units numeric,
    product_workload_share numeric,
    quality_control_pool_amount numeric not null,
    product_qc_allocation_amount numeric,
    product_base_uom text,
    product_absorption_base_qty numeric,
    absorption_basis_source text,
    absorption_basis_method text,
    absorption_basis_source_month date,
    absorption_basis_status text,
    absorption_basis_note text,
    qc_cost_per_product_base_uom numeric,
    allocation_status text not null,
    allocation_reason_code text not null,
    allocation_note text not null,
    recipient_product_count integer not null,
    included_product_count integer not null,
    excluded_product_count integer not null,
    resolved_coverage_ratio numeric not null,
    refreshed_at timestamptz not null default clock_timestamp(),
    constraint product_qc_allocation_snapshot_run_product_uq unique(refresh_run_id, product_id),
    constraint product_qc_allocation_snapshot_status_chk check (allocation_status in ('READY','REVIEW_REQUIRED','BLOCKED')),
    constraint product_qc_allocation_snapshot_counts_chk check (
      recipient_product_count > 0 and included_product_count >= 0 and excluded_product_count >= 0
      and included_product_count + excluded_product_count = recipient_product_count
    ),
    constraint product_qc_allocation_snapshot_ratio_chk check (resolved_coverage_ratio >= 0 and resolved_coverage_ratio <= 1),
    constraint product_qc_allocation_snapshot_share_chk check (product_workload_share is null or (product_workload_share > 0 and product_workload_share <= 1)),
    constraint product_qc_allocation_snapshot_amount_chk check (product_qc_allocation_amount is null or product_qc_allocation_amount >= 0),
    constraint product_qc_allocation_snapshot_absorption_qty_chk check (product_absorption_base_qty is null or product_absorption_base_qty > 0),
    constraint product_qc_allocation_snapshot_rate_chk check (qc_cost_per_product_base_uom is null or qc_cost_per_product_base_uom >= 0),
    constraint product_qc_allocation_snapshot_ready_values_chk check (
      allocation_status = 'BLOCKED'
      or (
        workload_units is not null and workload_units > 0
        and company_resolved_workload_units is not null and company_resolved_workload_units > 0
        and product_workload_share is not null and product_workload_share > 0
        and product_qc_allocation_amount is not null and product_qc_allocation_amount >= 0
        and product_absorption_base_qty is not null and product_absorption_base_qty > 0
        and qc_cost_per_product_base_uom is not null and qc_cost_per_product_base_uom >= 0
      )
    )
);

