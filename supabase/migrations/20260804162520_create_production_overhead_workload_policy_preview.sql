create table if not exists costing.production_overhead_workload_policy (
    id bigint generated by default as identity primary key,
    policy_code text not null,
    policy_version integer not null check (policy_version > 0),
    status text not null default 'DRAFT' check (status in ('DRAFT','REVIEW_REQUIRED','APPROVED','SUPERSEDED','INACTIVE')),
    effective_from date not null,
    effective_to date,
    formula_type text not null check (formula_type in ('BATCH_EQUIVALENT_ROUTE_FACTOR')),
    approval_reference text,
    policy_note text,
    approved_by uuid,
    approved_at timestamptz,
    created_by uuid,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(policy_code,policy_version),
    check (effective_to is null or effective_to >= effective_from)
);

create table if not exists costing.production_overhead_scope_factor (
    policy_id bigint not null references costing.production_overhead_workload_policy(id) on delete cascade,
    scope_code text not null check (scope_code in ('INCLUDE','PASSIVE','EXCLUDE_OTHER_POOL')),
    factor numeric not null check (factor >= 0),
    note text,
    primary key(policy_id,scope_code)
);

create table if not exists costing.production_overhead_behaviour_factor (
    policy_id bigint not null references costing.production_overhead_workload_policy(id) on delete cascade,
    behaviour_code text not null references costing.production_route_behaviour(code),
    factor numeric not null check (factor >= 0),
    note text,
    primary key(policy_id,behaviour_code)
);

create table if not exists costing.production_overhead_resource_factor (
    policy_id bigint not null references costing.production_overhead_workload_policy(id) on delete cascade,
    resource_class_code text not null references costing.production_resource_class(code),
    factor numeric not null check (factor >= 0),
    note text,
    primary key(policy_id,resource_class_code)
);

