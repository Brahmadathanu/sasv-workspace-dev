returns trigger
language plpgsql
set search_path to 'costing','public','pg_temp'
as $$
begin
    if tg_op='DELETE' then
        raise exception 'Production Overhead workload policies are append-only';
    end if;
    if old.status in ('APPROVED','SUPERSEDED','INACTIVE') then
        if to_jsonb(new) - array['status','effective_to','updated_at']::text[]
           is distinct from to_jsonb(old) - array['status','effective_to','updated_at']::text[] then
            raise exception 'Approved Production Overhead workload policy core fields are immutable; create a new version';
        end if;
    end if;
    new.updated_at:=now();
    return new;
end;
$$;

