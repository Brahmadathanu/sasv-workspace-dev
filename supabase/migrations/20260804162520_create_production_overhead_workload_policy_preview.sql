create or replace function costing.fn_resolve_production_overhead_workload_policy(p_as_of_date date)
returns costing.production_overhead_workload_policy
language plpgsql
stable security definer
set search_path to 'costing','public','pg_temp'
as $$
declare
    v_policy costing.production_overhead_workload_policy%rowtype;
    v_count integer;
begin
    if p_as_of_date is null then raise exception 'as_of_date is required'; end if;
    select count(*) into v_count
    from costing.production_overhead_workload_policy p
    where p.status='APPROVED'
      and p.effective_from<=p_as_of_date
      and (p.effective_to is null or p.effective_to>=p_as_of_date);
    if v_count<>1 then
        raise exception 'Exactly one approved Production Overhead workload policy must resolve for %, found %',p_as_of_date,v_count;
    end if;
    select * into v_policy
    from costing.production_overhead_workload_policy p
    where p.status='APPROVED'
      and p.effective_from<=p_as_of_date
      and (p.effective_to is null or p.effective_to>=p_as_of_date)
    order by p.effective_from desc,p.policy_version desc,p.id desc
    limit 1;
    return v_policy;
end;
$$;

create or replace function costing.fn_validate_production_overhead_workload_policy(p_policy_id bigint)
returns jsonb
language plpgsql
stable security definer
set search_path to 'costing','public','pg_temp'
as $$
declare
    v_errors jsonb:='[]'::jsonb;
    v_policy costing.production_overhead_workload_policy%rowtype;
    v_behaviour_count integer;
    v_resource_count integer;
begin
    select * into v_policy from costing.production_overhead_workload_policy where id=p_policy_id;
    if not found then return jsonb_build_object('valid',false,'errors',jsonb_build_array('POLICY_NOT_FOUND')); end if;

    if (select count(*) from costing.production_overhead_scope_factor where policy_id=p_policy_id)<>3 then
        v_errors:=v_errors||jsonb_build_array('REQUIRES_ALL_SCOPE_FACTORS');
    end if;
    if not exists(select 1 from costing.production_overhead_scope_factor where policy_id=p_policy_id and scope_code='INCLUDE' and factor>0) then
        v_errors:=v_errors||jsonb_build_array('INCLUDE_SCOPE_FACTOR_MUST_BE_POSITIVE');
    end if;
    if not exists(select 1 from costing.production_overhead_scope_factor where policy_id=p_policy_id and scope_code='EXCLUDE_OTHER_POOL' and factor=0) then
        v_errors:=v_errors||jsonb_build_array('EXCLUDED_SCOPE_FACTOR_MUST_BE_ZERO');
    end if;

    select count(*) into v_behaviour_count from costing.production_route_behaviour where is_active;
    if (select count(*) from costing.production_overhead_behaviour_factor where policy_id=p_policy_id)<>v_behaviour_count then
        v_errors:=v_errors||jsonb_build_array('REQUIRES_ALL_ACTIVE_BEHAVIOUR_FACTORS');
    end if;

    select count(*) into v_resource_count from costing.production_resource_class where is_active;
    if (select count(*) from costing.production_overhead_resource_factor where policy_id=p_policy_id)<>v_resource_count then
        v_errors:=v_errors||jsonb_build_array('REQUIRES_ALL_ACTIVE_RESOURCE_FACTORS');
    end if;

    return jsonb_build_object(
        'valid',jsonb_array_length(v_errors)=0,
        'errors',v_errors,
        'policy_id',p_policy_id,
        'status',v_policy.status,
        'scope_factor_count',(select count(*) from costing.production_overhead_scope_factor where policy_id=p_policy_id),
        'behaviour_factor_count',(select count(*) from costing.production_overhead_behaviour_factor where policy_id=p_policy_id),
        'resource_factor_count',(select count(*) from costing.production_overhead_resource_factor where policy_id=p_policy_id)
    );
end;
$$;

create or replace function costing.fn_preview_production_overhead_workload(
    p_policy_id bigint,
    p_period_start date,
    p_valuation_date date,
    p_refresh_run_id bigint,
    p_route_family_id bigint default null
)
returns jsonb
language plpgsql
stable security definer
set search_path to 'costing','public','pg_temp'
as $$
declare
    v_period_start date:=date_trunc('month',p_period_start)::date;
    v_run costing.costing_refresh_run%rowtype;
    v_policy costing.production_overhead_workload_policy%rowtype;
    v_result jsonb;
begin
    if p_policy_id is null or p_period_start is null or p_valuation_date is null or p_refresh_run_id is null then
        raise exception 'policy_id, period_start, valuation_date and refresh_run_id are required';
    end if;
    select * into v_policy from costing.production_overhead_workload_policy where id=p_policy_id;
    if not found then raise exception 'Production Overhead workload policy % not found',p_policy_id; end if;
    if not coalesce((costing.fn_validate_production_overhead_workload_policy(p_policy_id)->>'valid')::boolean,false) then
        raise exception 'Production Overhead workload policy % is invalid',p_policy_id;
    end if;
    select * into v_run from costing.costing_refresh_run where id=p_refresh_run_id;
    if not found then raise exception 'Costing refresh run % not found',p_refresh_run_id; end if;
    if v_run.period_start is distinct from v_period_start
       or v_run.valuation_date is distinct from p_valuation_date
       or v_run.valuation_context_source is distinct from 'CAPTURED_AT_REQUEST' then
        raise exception 'Preview context does not match refresh run %',p_refresh_run_id;
    end if;

    with recipients as (
        select b.product_id,
               max(b.product_name) as product_name,
               max(b.product_base_uom) as product_base_uom,
               max(b.monthly_product_allocation_base_qty) as monthly_product_base_qty,
               max(b.monthly_driver_status) as monthly_driver_status
        from costing.sku_sales_allocation_basis_snapshot b
        where b.period_start=v_period_start
          and b.valuation_date=p_valuation_date
          and b.refresh_run_id=p_refresh_run_id
        group by b.product_id
    ), products_in_scope as (
        select p.id as product_id,p.item as product_name,p.uom_base as product_base_uom,
               costing.fn_resolve_route_family_for_product(p.id,p_valuation_date) as route_family_id,
               costing.fn_resolve_effective_route_family_route(p.id,p_valuation_date) as family_route_id
        from public.products p
        where upper(coalesce(p.status,''))='ACTIVE'
          and (p_route_family_id is null or costing.fn_resolve_route_family_for_product(p.id,p_valuation_date)=p_route_family_id)
    ), batch_ref as (
        select distinct on (b.product_id)
               b.product_id,b.id as batch_size_ref_id,b.preferred_batch_size,b.effective_from
        from public.production_batch_size_ref b
        where b.is_active and b.effective_from<=p_valuation_date
        order by b.product_id,b.effective_from desc,b.id desc
    ), step_factor as (
        select p.product_id,
               count(*) as effective_step_count,
               count(*) filter(where e.production_overhead_scope='INCLUDE') as included_step_count,
               count(*) filter(where e.production_overhead_scope='PASSIVE') as passive_step_count,
               count(*) filter(where e.production_overhead_scope='EXCLUDE_OTHER_POOL') as excluded_step_count,
               sum(sf.factor*bf.factor*rf.factor*e.expected_occurrence_count*e.standard_cycle_count) as route_factor,
               jsonb_agg(jsonb_build_object(
                   'effective_step_key',e.effective_step_key,
                   'sequence_no',e.sequence_no,
                   'production_overhead_scope',e.production_overhead_scope,
                   'scope_factor',sf.factor,
                   'behaviour_code',e.behaviour_code,
                   'behaviour_factor',bf.factor,
                   'resource_class_code',e.resource_class_code,
                   'resource_factor',rf.factor,
                   'expected_occurrence_count',e.expected_occurrence_count,
                   'standard_cycle_count',e.standard_cycle_count,
                   'step_factor',sf.factor*bf.factor*rf.factor*e.expected_occurrence_count*e.standard_cycle_count,
                   'source_type',e.source_type
               ) order by e.sequence_no,e.effective_step_key) as step_evidence
        from products_in_scope p
        cross join lateral costing.fn_effective_product_process_steps(p.product_id,p_valuation_date) e
        join costing.production_overhead_scope_factor sf on sf.policy_id=p_policy_id and sf.scope_code=e.production_overhead_scope
        join costing.production_overhead_behaviour_factor bf on bf.policy_id=p_policy_id and bf.behaviour_code=e.behaviour_code
        join costing.production_overhead_resource_factor rf on rf.policy_id=p_policy_id and rf.resource_class_code=e.resource_class_code
        group by p.product_id
    ), rows as (
        select p.product_id,p.product_name,p.product_base_uom,p.route_family_id,p.family_route_id,
               r.monthly_product_base_qty,r.monthly_driver_status,
               b.batch_size_ref_id,b.preferred_batch_size,
               s.effective_step_count,s.included_step_count,s.passive_step_count,s.excluded_step_count,s.route_factor,s.step_evidence,
               case when b.preferred_batch_size>0 and r.monthly_product_base_qty is not null then r.monthly_product_base_qty/b.preferred_batch_size end as monthly_batch_equivalents,
               case when b.preferred_batch_size>0 and r.monthly_product_base_qty is not null then (r.monthly_product_base_qty/b.preferred_batch_size)*s.route_factor end as workload_units,
               case
                 when r.product_id is null then 'NOT_IN_CURRENT_RECIPIENT_SET'
                 when p.family_route_id is null then 'BLOCKED_NO_APPROVED_ROUTE_FAMILY_ROUTE'
                 when s.route_factor is null or s.route_factor<=0 then 'BLOCKED_NO_POSITIVE_ROUTE_FACTOR'
                 when b.batch_size_ref_id is null or b.preferred_batch_size<=0 then 'BLOCKED_NO_ACTIVE_BATCH_SIZE'
                 when r.monthly_product_base_qty is null or r.monthly_product_base_qty<=0 then 'BLOCKED_NO_MONTHLY_PRODUCT_BASE_QTY'
                 when r.monthly_driver_status='BLOCKED' then 'BLOCKED_MONTHLY_DRIVER'
                 when r.monthly_driver_status='REVIEW_REQUIRED' then 'REVIEW_REQUIRED_MONTHLY_DRIVER'
                 else 'READY'
               end as workload_status
        from products_in_scope p
        left join recipients r on r.product_id=p.product_id
        left join batch_ref b on b.product_id=p.product_id
        left join step_factor s on s.product_id=p.product_id
    )
    select jsonb_build_object(
        'preview_only',true,
        'approvable',false,
        'records_created',0,
        'policy',to_jsonb(v_policy),
        'period_start',v_period_start,
        'valuation_date',p_valuation_date,
        'refresh_run_id',p_refresh_run_id,
        'route_family_id',p_route_family_id,
        'summary',jsonb_build_object(
            'product_count',count(*),
            'ready_count',count(*) filter(where workload_status='READY'),
            'review_required_count',count(*) filter(where workload_status like 'REVIEW_REQUIRED%'),
            'blocked_count',count(*) filter(where workload_status like 'BLOCKED%'),
            'not_in_recipient_set_count',count(*) filter(where workload_status='NOT_IN_CURRENT_RECIPIENT_SET'),
            'company_ready_workload_units',sum(workload_units) filter(where workload_status in ('READY','REVIEW_REQUIRED_MONTHLY_DRIVER'))
        ),
        'status_counts',coalesce((select jsonb_object_agg(workload_status,cnt) from (select workload_status,count(*) cnt from rows group by workload_status) x),'{}'::jsonb),
        'rows',coalesce(jsonb_agg(to_jsonb(rows) order by product_name,product_id),'[]'::jsonb)
    ) into v_result
    from rows;
    return v_result;
end;
$$;

