create or replace function regulatory.normalize_controlled_term_alias(p_text text)
returns text
language sql
immutable
strict
set search_path = ''
as $function$
  select lower(regexp_replace(btrim(p_text), '[[:space:]]+', ' ', 'g'));
$function$;

comment on function regulatory.normalize_controlled_term_alias(text) is
  'Conservative controlled-term alias normalizer: trim, collapse whitespace, lowercase; punctuation and diacritics are preserved.';

create table regulatory.controlled_term_alias (
  id bigint generated by default as identity primary key,
  domain_code text not null,
  controlled_term_id bigint not null,
  alias_text text not null,
  alias_key text generated always as (regulatory.normalize_controlled_term_alias(alias_text)) stored,
  mapping_status text not null,
  match_basis text,
  comparison_evidence jsonb not null default '{}'::jsonb,
  mapping_reason text,
  effective_from timestamptz,
  effective_to timestamptz,
  verified_by uuid,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid,
  updated_at timestamptz not null default now(),
  updated_by uuid,
  constraint controlled_term_alias_domain_fk
    foreign key (controlled_term_id, domain_code)
    references regulatory.controlled_term(id, domain_code)
    on delete restrict,
  constraint controlled_term_alias_status_check
    check (mapping_status in ('DRAFT','VERIFIED','REJECTED','SUPERSEDED')),
  constraint controlled_term_alias_text_nonblank check (btrim(alias_text) <> ''),
  constraint controlled_term_alias_key_nonblank check (btrim(alias_key) <> ''),
  constraint controlled_term_alias_window_check
    check (effective_to is null or effective_from is null or effective_to > effective_from),
  constraint controlled_term_alias_verification_check
    check (
      (mapping_status = 'VERIFIED' and verified_by is not null and verified_at is not null)
      or
      (mapping_status <> 'VERIFIED' and verified_by is null and verified_at is null)
    )
);

comment on table regulatory.controlled_term_alias is
  'Global governed mapping from observed source wording to a canonical controlled term. Product and line identity do not participate in alias authority.';

create unique index uq_controlled_term_alias_current
  on regulatory.controlled_term_alias(domain_code, alias_key)
