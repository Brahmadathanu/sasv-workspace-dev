create or replace function costing.rpc_refresh_sku_regional_marketing_expense_allocation_snapshot(
    p_period_start date,
    p_valuation_date date,
    p_refresh_run_id bigint
)
returns table (
    refreshed_period_start date,
    inserted_row_count bigint,
    blocked_count bigint,
    review_required_count bigint,
    ready_count bigint
)
language plpgsql
security definer
set search_path = costing, public, pg_temp
as $function$
declare
    v_period_start date := date_trunc('month', p_period_start)::date;
    v_run costing.costing_refresh_run%rowtype;
    v_basis_count bigint;
    v_distinct_key_count bigint;
    v_ambiguous_product_region_count bigint;
    v_resolved_company_value numeric;
    v_pool_amount numeric;
begin
    if p_period_start is null then
        raise exception 'Costing period is required.';
    end if;
    if p_valuation_date is null then
        raise exception 'Valuation date is required.';
    end if;
    if p_refresh_run_id is null then
        raise exception 'Refresh run ID is required.';
    end if;

    select * into v_run
    from costing.costing_refresh_run r
    where r.id = p_refresh_run_id;

    if not found then
        raise exception 'Costing refresh run % does not exist.', p_refresh_run_id;
    end if;

    if v_run.period_start is distinct from v_period_start
       or v_run.valuation_date is distinct from p_valuation_date then
        raise exception 'Regional Marketing allocation context does not match refresh run %.', p_refresh_run_id;
    end if;

    if v_run.valuation_context_source is distinct from 'CAPTURED_AT_REQUEST' then
        raise exception 'Refresh run % is not based on captured-at-request valuation context.', p_refresh_run_id;
    end if;

    if v_run.overall_status not in ('QUEUED','RUNNING','FAILED') then
        raise exception 'Regional Marketing allocation cannot be refreshed for terminal run % with status %.', p_refresh_run_id, v_run.overall_status;
    end if;

    select count(*)::bigint,
           count(distinct (b.sku_id, b.region_code))::bigint
    into v_basis_count, v_distinct_key_count
    from costing.sku_regional_marketing_allocation_basis_snapshot b
    where b.period_start = v_period_start
      and b.valuation_date = p_valuation_date
      and b.refresh_run_id = p_refresh_run_id;

    if v_basis_count = 0 then
        raise exception 'Regional Marketing physical basis is missing for refresh run %.', p_refresh_run_id;
    end if;

    if v_basis_count <> v_distinct_key_count then
        raise exception 'Regional Marketing physical basis contains duplicate SKU-region rows for refresh run %.', p_refresh_run_id;
    end if;

    select m.total_pool_amount
    into v_pool_amount
    from costing.v_cost_pool_monthly_combined m
    where m.period_start = v_period_start
      and m.allocation_pool = 'MARKETING_EXPENSE';

    if v_pool_amount is null then
        raise exception 'Marketing expense pool is missing for period %.', v_period_start;
    end if;

    with pr as (
        select
            b.product_id,
            b.region_code,
            max(b.product_region_actual_evidence_row_count) as actual_row_count,
            max(b.product_region_actual_signed_billed_value) as actual_value,
            count(*) filter (
                where b.product_region_actual_evidence_row_count = 0
                  and b.assumption_resolution_status = 'AMBIGUOUS'
            )::bigint as ambiguous_count
        from costing.sku_regional_marketing_allocation_basis_snapshot b
        where b.refresh_run_id = p_refresh_run_id
        group by b.product_id, b.region_code
    )
    select count(*)::bigint
    into v_ambiguous_product_region_count
    from pr
    where actual_row_count = 0
      and ambiguous_count > 0;

    if v_ambiguous_product_region_count > 0 then
        raise exception '% Product-region context(s) contain ambiguous visible regional assumptions for refresh run %.', v_ambiguous_product_region_count, p_refresh_run_id;
    end if;

    with pr as (
        select
            b.product_id,
            b.region_code,
            max(b.product_region_actual_evidence_row_count) as actual_row_count,
            max(b.product_region_actual_signed_billed_value) as actual_value,
            coalesce(sum(b.assumed_sales_value) filter (
                where b.product_region_actual_evidence_row_count = 0
                  and b.assumption_resolution_status = 'RESOLVED'
            ),0::numeric) as assumed_value,
            count(*) filter (
                where b.product_region_actual_evidence_row_count = 0
                  and b.assumption_resolution_status = 'RESOLVED'
            )::bigint as assumption_count
        from costing.sku_regional_marketing_allocation_basis_snapshot b
        where b.refresh_run_id = p_refresh_run_id
        group by b.product_id, b.region_code
    ), resolved as (
        select case
            when actual_row_count > 0 then actual_value
            when assumption_count > 0 then assumed_value
            else 0::numeric
        end as resolved_value
        from pr
    )
    select coalesce(sum(resolved_value),0::numeric)
    into v_resolved_company_value
    from resolved;

    if v_resolved_company_value = 0 then
        raise exception 'Resolved company regional Marketing sales value is zero for refresh run %.', p_refresh_run_id;
    end if;

    delete from costing.sku_regional_marketing_expense_allocation_snapshot s
    where s.refresh_run_id = p_refresh_run_id;

    insert into costing.sku_regional_marketing_expense_allocation_snapshot (
        period_start, valuation_date, refresh_run_id,
        regional_basis_snapshot_id, common_allocation_basis_snapshot_id,
        sku_id, product_id, product_name,
        region_id, region_code,
        pack_size, pack_uom, sku_base_qty_per_unit,
        marketing_driver_code,
        product_region_actual_evidence_row_count,
        product_region_actual_signed_billed_value,
        regional_assumption_count,
        regional_assumption_ids,
        regional_assumption_approval_references,
        regional_assumed_sales_value,
        marketing_value_source,
        resolved_product_region_marketing_sales_value,
        resolved_company_marketing_sales_value,
        product_region_monetary_allocation_share,
        marketing_pool_amount,
        product_region_marketing_allocation,
        recipient_product_region_base_qty,
        resolved_regional_units,
        resolved_regional_base_qty,
        regional_basis_source,
        regional_basis_status,
        regional_basis_note,
        marketing_expense_cost_per_sku_region,
        marketing_expense_allocation_status,
        marketing_expense_allocation_note,
        marketing_lookback_start,
        marketing_lookback_end,
        marketing_source_cutoff_at,
        refreshed_at
    )
    with product_region as materialized (
        select
            b.product_id,
            b.region_id,
            b.region_code,
            max(b.product_region_actual_evidence_row_count)::bigint as actual_row_count,
            max(b.product_region_actual_signed_billed_value)::numeric as actual_value,
            count(*) filter (
                where b.product_region_actual_evidence_row_count = 0
                  and b.assumption_resolution_status = 'RESOLVED'
            )::bigint as assumption_count,
            coalesce(jsonb_agg(b.regional_assumption_id order by b.sku_id)
                filter (where b.product_region_actual_evidence_row_count = 0
                        and b.assumption_resolution_status = 'RESOLVED'
                        and b.regional_assumption_id is not null),'[]'::jsonb) as assumption_ids,
            coalesce(jsonb_agg(b.assumption_approval_reference order by b.sku_id)
                filter (where b.product_region_actual_evidence_row_count = 0
                        and b.assumption_resolution_status = 'RESOLVED'
                        and b.assumption_approval_reference is not null),'[]'::jsonb) as approval_references,
            coalesce(sum(b.assumed_sales_value) filter (
                where b.product_region_actual_evidence_row_count = 0
                  and b.assumption_resolution_status = 'RESOLVED'
            ),0::numeric) as assumed_value,
            sum(b.resolved_regional_base_qty) filter (
                where b.regional_basis_status in ('READY','REVIEW_REQUIRED')
                  and b.resolved_regional_base_qty > 0
            )::numeric as recipient_base_qty
        from costing.sku_regional_marketing_allocation_basis_snapshot b
        where b.period_start = v_period_start
          and b.valuation_date = p_valuation_date
          and b.refresh_run_id = p_refresh_run_id
        group by b.product_id, b.region_id, b.region_code
    ), resolved_product_region as materialized (
        select
            p.*,
            case
                when p.actual_row_count > 0 then 'ACTUAL_SIGNED_BILLED_SALES'
                when p.assumption_count > 0 then 'APPROVED_REGIONAL_ASSUMPTION'
                else 'NO_ELIGIBLE_HISTORY'
            end as value_source,
            case
                when p.actual_row_count > 0 then p.actual_value
                when p.assumption_count > 0 then p.assumed_value
                else 0::numeric
            end as resolved_value
        from product_region p
    )
    select
        b.period_start,
        b.valuation_date,
        b.refresh_run_id,
        b.id,
        b.allocation_basis_snapshot_id,
        b.sku_id,
        b.product_id,
        b.product_name,
        b.region_id,
        b.region_code,
        b.pack_size,
        b.pack_uom,
        b.sku_base_qty_per_unit,
        'MARKETING_SIGNED_BILLED_SALES_VALUE',
        p.actual_row_count,
        p.actual_value,
        p.assumption_count,
        p.assumption_ids,
        p.approval_references,
        case when p.assumption_count > 0 then p.assumed_value else null::numeric end,
        p.value_source,
        p.resolved_value,
        v_resolved_company_value,
        p.resolved_value / v_resolved_company_value,
        v_pool_amount,
        v_pool_amount * (p.resolved_value / v_resolved_company_value),
        p.recipient_base_qty,
        b.resolved_regional_units,
        b.resolved_regional_base_qty,
        b.regional_basis_source,
        b.regional_basis_status,
        b.regional_basis_note,
        case
            when b.regional_basis_status = 'BLOCKED' then null::numeric
            when p.value_source = 'NO_ELIGIBLE_HISTORY' then 0::numeric
            when p.recipient_base_qty is null or p.recipient_base_qty <= 0 then null::numeric
            when b.sku_base_qty_per_unit is null or b.sku_base_qty_per_unit <= 0 then null::numeric
            else (
                v_pool_amount * (p.resolved_value / v_resolved_company_value)
                / p.recipient_base_qty
            ) * b.sku_base_qty_per_unit
        end,
        case
            when b.regional_basis_status = 'BLOCKED' then 'BLOCKED'
            when p.recipient_base_qty is null or p.recipient_base_qty <= 0 then 'BLOCKED'
            when b.sku_base_qty_per_unit is null or b.sku_base_qty_per_unit <= 0 then 'BLOCKED'
            when p.value_source = 'APPROVED_REGIONAL_ASSUMPTION' then 'REVIEW_REQUIRED'
            when p.value_source = 'NO_ELIGIBLE_HISTORY' then 'REVIEW_REQUIRED'
            when p.actual_value <= 0 then 'REVIEW_REQUIRED'
            when b.regional_basis_status = 'REVIEW_REQUIRED' then 'REVIEW_REQUIRED'
            else 'READY'
        end,
        case
            when b.regional_basis_status = 'BLOCKED' then
                'Regional Marketing allocation is blocked because the governed SKU-region physical basis is blocked.'
            when p.recipient_base_qty is null or p.recipient_base_qty <= 0 then
                'Regional Marketing allocation is blocked because the Product × Region recipient base quantity is missing or nonpositive.'
            when b.sku_base_qty_per_unit is null or b.sku_base_qty_per_unit <= 0 then
                'Regional Marketing allocation is blocked because SKU base quantity per unit is missing or nonpositive.'
            when p.value_source = 'APPROVED_REGIONAL_ASSUMPTION' then
                'No eligible actual Product × Region sales rows exist; the monetary share uses governed regional assumptions visible at the exact refresh-run cutoff and requires review.'
            when p.value_source = 'NO_ELIGIBLE_HISTORY' then
                'No eligible actual Product × Region sales rows or governed regional assumptions exist. Regional Marketing allocation is zero and requires review.'
            when p.actual_value <= 0 then
                'Actual eligible Product × Region signed billed value is zero or negative. Actual monetary precedence is retained and requires review.'
            when b.regional_basis_status = 'REVIEW_REQUIRED' then
                'Actual Product × Region monetary share is combined with a governed assumed or region-scaled physical basis and requires review.'
            else
                'Regional Marketing expense uses Product × Region signed tax-exclusive billed value between Product × Region contexts and the governed regional base quantity within the Product × Region.'
        end,
        (v_period_start - interval '12 months')::date,
        v_period_start,
        v_run.requested_at,
        clock_timestamp()
    from costing.sku_regional_marketing_allocation_basis_snapshot b
    join resolved_product_region p
      on p.product_id = b.product_id
     and p.region_code = b.region_code
    where b.period_start = v_period_start
      and b.valuation_date = p_valuation_date
      and b.refresh_run_id = p_refresh_run_id;

    return query
    select
        v_period_start,
        count(*)::bigint,
        count(*) filter (where s.marketing_expense_allocation_status='BLOCKED')::bigint,
        count(*) filter (where s.marketing_expense_allocation_status='REVIEW_REQUIRED')::bigint,
        count(*) filter (where s.marketing_expense_allocation_status='READY')::bigint
    from costing.sku_regional_marketing_expense_allocation_snapshot s
    where s.period_start = v_period_start
      and s.valuation_date = p_valuation_date
      and s.refresh_run_id = p_refresh_run_id;
end;
$function$;

