create table if not exists costing.direct_labour_workload_policy (
    id bigint generated by default as identity primary key,
    policy_code text not null,
    policy_version integer not null,
    status text not null check (status in ('DRAFT','REVIEW_REQUIRED','APPROVED','SUPERSEDED','INACTIVE')),
    effective_from date not null,
    effective_to date,
    formula_type text not null check (formula_type='STANDARD_BATCH_ROUTE_ATTENDANCE'),
    approval_reference text,
    policy_note text not null,
    approved_by uuid,
    approved_at timestamptz,
    created_by uuid,
    created_at timestamptz not null default clock_timestamp(),
    updated_at timestamptz not null default clock_timestamp(),
    unique(policy_code,policy_version),
    check (effective_to is null or effective_to>=effective_from),
    check ((status='APPROVED' and approval_reference is not null and approved_at is not null)
        or status<>'APPROVED')
);

create table if not exists costing.direct_labour_scope_factor (
    policy_id bigint not null references costing.direct_labour_workload_policy(id),
    scope_code text not null check (scope_code in ('INCLUDE','SUPERVISION','EXCLUDE_OTHER_POOL')),
    factor numeric not null check (factor>=0),
    note text not null,
    primary key(policy_id,scope_code)
);

create table if not exists costing.direct_labour_behaviour_factor (
    policy_id bigint not null references costing.direct_labour_workload_policy(id),
    behaviour_code text not null references costing.production_route_behaviour(code),
    factor numeric not null check (factor>=0),
    note text not null,
    primary key(policy_id,behaviour_code)
);

create or replace function costing.fn_guard_direct_labour_workload_policy()
returns trigger language plpgsql
set search_path=costing,public,pg_temp
as $$
begin
    if tg_op='DELETE' then
        raise exception 'Direct Labour workload policies are append-only';
    end if;
    if old.status in ('APPROVED','SUPERSEDED','INACTIVE') then
        if to_jsonb(new)-array['status','effective_to','updated_at']::text[]
           is distinct from to_jsonb(old)-array['status','effective_to','updated_at']::text[] then
            raise exception 'Approved or closed Direct Labour policy core fields are immutable; create a new version';
        end if;
    end if;
    new.updated_at:=clock_timestamp();
    return new;
end;
$$;

