-- Gate A: PLM PM-BOM temporal governance foundation
-- Additive only. No bootstrap data. No costing flip. No UI.
-- Overlap EXCLUDE covers APPROVED + SUPERSEDED.
-- As-of resolves APPROVED + SUPERSEDED only.

-- ---------------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------------

create table public.plm_bom_revision (
  id bigint generated by default as identity primary key,
  sku_id bigint not null references public.product_skus (id),
  revision_no integer not null,
  status text not null,
  effective_from date not null,
  effective_to date,
  source_tpl_id bigint references public.plm_tpl_header (id) on delete set null,
  frozen_reference_output_qty numeric not null,
  frozen_reference_output_uom_id bigint not null references public.inv_uom (id),
  frozen_process_loss_pct numeric not null,
  change_reason text,
  approval_reference text,
  supersedes_revision_id bigint references public.plm_bom_revision (id),
  content_hash text,
  frozen_at timestamptz,
  created_at timestamptz not null default clock_timestamp(),
  created_by uuid default auth.uid(),
  approved_at timestamptz,
  approved_by uuid,
  superseded_at timestamptz,
  superseded_by uuid,
  cancelled_at timestamptz,
  cancelled_by uuid,
  constraint plm_bom_revision_status_chk
    check (status = any (array['DRAFT'::text, 'APPROVED'::text, 'SUPERSEDED'::text, 'CANCELLED'::text])),
  constraint plm_bom_revision_dates_chk
    check ((effective_to is null) or (effective_to >= effective_from)),
  constraint plm_bom_revision_revision_no_chk
    check (revision_no > 0),
  constraint plm_bom_revision_qty_chk
    check (frozen_reference_output_qty > 0::numeric),
  constraint plm_bom_revision_loss_chk
    check (frozen_process_loss_pct >= 0::numeric),
  constraint plm_bom_revision_sku_rev_uq unique (sku_id, revision_no)
);

create table public.plm_bom_revision_line (
  id bigint generated by default as identity primary key,
  revision_id bigint not null references public.plm_bom_revision (id) on delete cascade,
  line_no integer not null,
  stock_item_id bigint not null references public.inv_stock_item (id),
  qty_per_reference_output numeric not null,
  uom_id bigint not null references public.inv_uom (id),
  wastage_pct numeric,
  is_optional boolean not null default false,
  is_override boolean not null default false,
  source_op text,
  remarks text,
  constraint plm_bom_revision_line_line_no_chk check (line_no > 0),
  constraint plm_bom_revision_line_qty_chk check (qty_per_reference_output > 0::numeric),
  constraint plm_bom_revision_line_wastage_chk
    check ((wastage_pct is null) or (wastage_pct >= 0::numeric)),
  constraint plm_bom_revision_line_rev_line_uq unique (revision_id, line_no),
  constraint plm_bom_revision_line_rev_item_uom_uq unique (revision_id, stock_item_id, uom_id)
);

create index ix_plm_bom_revision_sku_status_dates
  on public.plm_bom_revision (sku_id, status, effective_from, effective_to);

create index ix_plm_bom_revision_line_revision
  on public.plm_bom_revision_line (revision_id, line_no);

-- At most one open current APPROVED revision per SKU
create unique index uq_plm_bom_revision_one_open_approved
  on public.plm_bom_revision (sku_id)
  where (status = 'APPROVED' and effective_to is null);

-- Governed validity windows must not overlap (APPROVED + SUPERSEDED)
alter table public.plm_bom_revision
  add constraint plm_bom_revision_no_governed_overlap
  exclude using gist (
    sku_id with =,
    daterange(effective_from, coalesce(effective_to, 'infinity'::date), '[]') with &&
  )
  where (status = any (array['APPROVED'::text, 'SUPERSEDED'::text]));

comment on table public.plm_bom_revision is
  'Gate A governed SKU PM-BOM revision header. SUPERSEDED remains historically valid for as-of resolution.';
comment on table public.plm_bom_revision_line is
  'Frozen lines for a PM-BOM revision. Immutable once parent is APPROVED or SUPERSEDED.';

