$function$;

create or replace function public.rpc_plm_bom_revision_list_lines(p_revision_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'public', 'pg_temp'
as $function$
begin
  perform public.require_permission('module:pm-templates', false);

  if not exists (select 1 from public.plm_bom_revision r where r.id = p_revision_id) then
    raise exception 'Revision % not found', p_revision_id;
  end if;

  return coalesce(
    (
      select jsonb_agg(
        jsonb_build_object(
          'id', l.id,
          'revision_id', l.revision_id,
          'line_no', l.line_no,
          'stock_item_id', l.stock_item_id,
          'stock_item_name', i.name,
          'qty_per_reference_output', l.qty_per_reference_output,
          'uom_id', l.uom_id,
          'uom_code', u.code,
          'wastage_pct', l.wastage_pct,
          'is_optional', l.is_optional,
          'is_override', l.is_override,
          'source_op', l.source_op,
          'remarks', l.remarks
        )
        order by l.line_no
      )
      from public.plm_bom_revision_line l
      left join public.inv_stock_item i on i.id = l.stock_item_id
      left join public.inv_uom u on u.id = l.uom_id
      where l.revision_id = p_revision_id
    ),
    '[]'::jsonb
  );
end;
$function$;

