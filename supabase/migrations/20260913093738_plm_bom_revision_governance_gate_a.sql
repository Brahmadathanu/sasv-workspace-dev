create or replace function public.rpc_plm_bom_revision_create_draft(
  p_sku_id bigint,
  p_effective_from date default current_date
)
returns bigint
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_revision_id bigint;
  v_revision_no integer;
  v_tpl_id bigint;
  v_qty numeric;
  v_uom_id bigint;
  v_loss numeric;
  v_line_count integer := 0;
begin
  perform public.require_permission('module:pm-templates', true);

  if p_sku_id is null then
    raise exception 'p_sku_id is required';
  end if;
  if p_effective_from is null then
    raise exception 'p_effective_from is required';
  end if;

  if not exists (select 1 from public.product_skus s where s.id = p_sku_id) then
    raise exception 'SKU % not found', p_sku_id;
  end if;

  perform pg_advisory_xact_lock(87201401, (abs(p_sku_id) % 2147483647)::integer);

  select m.tpl_id into v_tpl_id
  from public.plm_sku_pack_map m
  where m.sku_id = p_sku_id;

  select h.reference_output_qty, h.reference_output_uom_id, h.process_loss_pct
  into v_qty, v_uom_id, v_loss
  from public.plm_bom_header h
  where h.sku_id = p_sku_id;

  if v_qty is null then
    select t.reference_output_qty, t.reference_output_uom_id, t.process_loss_pct
    into v_qty, v_uom_id, v_loss
    from public.plm_tpl_header t
    where t.id = v_tpl_id;
  end if;

  if v_qty is null or v_uom_id is null or v_loss is null then
    raise exception 'Cannot freeze draft for SKU %: missing reference output / process loss from compiled BOM or mapped template', p_sku_id;
  end if;

  select coalesce(max(r.revision_no), 0) + 1
  into v_revision_no
  from public.plm_bom_revision r
  where r.sku_id = p_sku_id;

  insert into public.plm_bom_revision (
    sku_id,
    revision_no,
    status,
    effective_from,
    source_tpl_id,
    frozen_reference_output_qty,
    frozen_reference_output_uom_id,
    frozen_process_loss_pct,
    created_by
  ) values (
    p_sku_id,
    v_revision_no,
    'DRAFT',
    p_effective_from,
    v_tpl_id,
    v_qty,
    v_uom_id,
    v_loss,
    auth.uid()
  )
  returning id into v_revision_id;

  insert into public.plm_bom_revision_line (
    revision_id,
    line_no,
    stock_item_id,
    qty_per_reference_output,
    uom_id,
    wastage_pct,
    is_optional,
    is_override,
    source_op
  )
  select
    v_revision_id,
    row_number() over (order by e.stock_item_id, e.uom_id)::integer,
    e.stock_item_id,
    e.qty_per_reference_output,
    e.uom_id,
    e.wastage_pct,
    coalesce(e.is_optional, false),
    coalesce(e.is_override, false),
    case when coalesce(e.is_override, false) then 'override' else 'template' end
  from public.plm_sku_bom_effective(p_sku_id) e;

  get diagnostics v_line_count = row_count;

  if v_line_count = 0 then
    raise exception 'Cannot create draft for SKU %: effective PM BOM has no lines', p_sku_id;
  end if;

  return v_revision_id;
end;
$function$;

create or replace function public.rpc_plm_bom_revision_cancel(p_revision_id bigint)
returns void
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_row public.plm_bom_revision%rowtype;
begin
  perform public.require_permission('module:pm-templates', true);

  select * into v_row
  from public.plm_bom_revision
  where id = p_revision_id
  for update;

  if not found then
    raise exception 'Revision % not found', p_revision_id;
  end if;

  if v_row.status <> 'DRAFT' then
    raise exception 'Only DRAFT revisions may be cancelled (revision % is %)', p_revision_id, v_row.status;
  end if;

  update public.plm_bom_revision
  set status = 'CANCELLED',
      cancelled_at = clock_timestamp(),
      cancelled_by = auth.uid()
  where id = p_revision_id;
end;
$function$;

create or replace function public.rpc_plm_bom_revision_approve(
  p_revision_id bigint,
  p_effective_from date,
  p_change_reason text,
  p_approval_reference text default null
)
returns jsonb
language plpgsql
security definer
