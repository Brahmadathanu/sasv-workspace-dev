create or replace function public.fn_plm_bom_revision_header_immutable()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_governed boolean := public.fn_plm_bom_revision_governed_context();
begin
  if tg_op = 'DELETE' then
    if old.status in ('APPROVED', 'SUPERSEDED') then
      raise exception 'Cannot delete % PM-BOM revision %', old.status, old.id;
    end if;
    return old;
  end if;

  if tg_op = 'UPDATE' then
    if old.status = 'CANCELLED' then
      raise exception 'Cannot update CANCELLED PM-BOM revision %', old.id;
    end if;

    if old.status = 'SUPERSEDED' then
      raise exception 'Cannot update SUPERSEDED PM-BOM revision %', old.id;
    end if;

    if old.status = 'APPROVED' then
      if not v_governed then
        raise exception 'Cannot update APPROVED PM-BOM revision % outside governed approval context', old.id;
      end if;

      -- Only controlled successor close transition: APPROVED -> SUPERSEDED
      if new.status is distinct from 'SUPERSEDED'
         or new.sku_id is distinct from old.sku_id
         or new.revision_no is distinct from old.revision_no
         or new.effective_from is distinct from old.effective_from
         or new.source_tpl_id is distinct from old.source_tpl_id
         or new.frozen_reference_output_qty is distinct from old.frozen_reference_output_qty
         or new.frozen_reference_output_uom_id is distinct from old.frozen_reference_output_uom_id
         or new.frozen_process_loss_pct is distinct from old.frozen_process_loss_pct
         or new.content_hash is distinct from old.content_hash
         or new.frozen_at is distinct from old.frozen_at
         or new.created_at is distinct from old.created_at
         or new.created_by is distinct from old.created_by
         or new.approved_at is distinct from old.approved_at
         or new.approved_by is distinct from old.approved_by
         or new.change_reason is distinct from old.change_reason
         or new.approval_reference is distinct from old.approval_reference
         or new.supersedes_revision_id is distinct from old.supersedes_revision_id
         or new.cancelled_at is distinct from old.cancelled_at
         or new.cancelled_by is distinct from old.cancelled_by
      then
        raise exception 'Governed update of APPROVED PM-BOM revision % may only supersede and close effective_to', old.id;
      end if;

      if new.effective_to is null then
        raise exception 'Superseding PM-BOM revision % requires effective_to', old.id;
      end if;

      if new.superseded_at is null then
        raise exception 'Superseding PM-BOM revision % requires superseded_at', old.id;
      end if;

      return new;
    end if;

    -- DRAFT updates (including DRAFT -> APPROVED / CANCELLED) allowed;
    -- DRAFT -> APPROVED must run under governed context from approve RPC.
    if old.status = 'DRAFT' and new.status = 'APPROVED' and not v_governed then
      raise exception 'Approving PM-BOM revision % requires governed approval RPC context', old.id;
    end if;
  end if;

  return new;
end;
$function$;

create or replace function public.fn_plm_bom_revision_line_immutable()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_status text;
  v_revision_id bigint;
begin
  v_revision_id := coalesce(new.revision_id, old.revision_id);

  select r.status into v_status
  from public.plm_bom_revision r
  where r.id = v_revision_id;

  if v_status is null then
    raise exception 'PM-BOM revision % not found for line guard', v_revision_id;
  end if;

  if v_status in ('APPROVED', 'SUPERSEDED') then
    raise exception 'Cannot % lines of % PM-BOM revision %', lower(tg_op), v_status, v_revision_id;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$function$;

