create or replace function public.fn_plm_bom_revision_build_content_hash(
  p_sku_id bigint,
  p_effective_from date,
  p_frozen_reference_output_qty numeric,
  p_frozen_reference_output_uom_id bigint,
  p_frozen_process_loss_pct numeric,
  p_source_tpl_id bigint,
  p_lines jsonb
)
returns text
language plpgsql
immutable
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_header text;
  v_lines text;
  v_line jsonb;
  v_parts text[] := array[]::text[];
  v_sorted jsonb;
begin
  if p_sku_id is null or p_effective_from is null then
    raise exception 'content_hash requires sku_id and effective_from';
  end if;

  v_header := concat_ws(
    '|',
    'sku=' || p_sku_id::text,
    'from=' || p_effective_from::text,
    'qty=' || trim(to_char(p_frozen_reference_output_qty, 'FM999999999999999999999999990.999999999999')),
    'uom=' || p_frozen_reference_output_uom_id::text,
    'loss=' || trim(to_char(p_frozen_process_loss_pct, 'FM999999999999999999999999990.999999999999')),
    'tpl=' || coalesce(p_source_tpl_id::text, '')
  );

  v_sorted := coalesce(
    (
      select jsonb_agg(x.elem order by (x.elem->>'line_no')::integer)
      from jsonb_array_elements(coalesce(p_lines, '[]'::jsonb)) as x(elem)
    ),
    '[]'::jsonb
  );

  for v_line in select * from jsonb_array_elements(v_sorted)
  loop
    v_parts := array_append(
      v_parts,
      concat_ws(
        '|',
        'ln=' || coalesce(v_line->>'line_no', ''),
        'item=' || coalesce(v_line->>'stock_item_id', ''),
        'qty=' || trim(to_char(coalesce((v_line->>'qty_per_reference_output')::numeric, 0), 'FM999999999999999999999999990.999999999999')),
        'uom=' || coalesce(v_line->>'uom_id', ''),
        'wast=' || case
          when v_line->>'wastage_pct' is null or v_line->>'wastage_pct' = '' then ''
          else trim(to_char((v_line->>'wastage_pct')::numeric, 'FM999999999999999999999999990.999999999999'))
        end,
        'opt=' || coalesce(v_line->>'is_optional', 'false'),
        'ovr=' || coalesce(v_line->>'is_override', 'false'),
        'op=' || coalesce(v_line->>'source_op', '')
      )
    );
  end loop;

  v_lines := array_to_string(v_parts, E'\n');
  return md5(v_header || E'\n' || v_lines);
end;
$function$;

create or replace function public.fn_plm_bom_revision_compute_content_hash(p_revision_id bigint)
returns text
language plpgsql
stable
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_h public.plm_bom_revision%rowtype;
  v_lines jsonb;
begin
  select * into v_h
  from public.plm_bom_revision
  where id = p_revision_id;

  if not found then
    raise exception 'Revision % not found', p_revision_id;
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'line_no', l.line_no,
        'stock_item_id', l.stock_item_id,
        'qty_per_reference_output', l.qty_per_reference_output,
        'uom_id', l.uom_id,
        'wastage_pct', l.wastage_pct,
        'is_optional', l.is_optional,
        'is_override', l.is_override,
        'source_op', l.source_op
      )
      order by l.line_no
    ),
    '[]'::jsonb
  )
  into v_lines
  from public.plm_bom_revision_line l
  where l.revision_id = p_revision_id;

  return public.fn_plm_bom_revision_build_content_hash(
    v_h.sku_id,
    v_h.effective_from,
    v_h.frozen_reference_output_qty,
    v_h.frozen_reference_output_uom_id,
    v_h.frozen_process_loss_pct,
    v_h.source_tpl_id,
    v_lines
  );
end;
$function$;

create or replace function public.fn_plm_bom_revision_verify_content_hash(p_revision_id bigint)
returns boolean
language sql
stable
set search_path to 'public', 'pg_temp'
as $function$
  select r.content_hash is not null
     and r.content_hash = public.fn_plm_bom_revision_compute_content_hash(r.id)
  from public.plm_bom_revision r
  where r.id = p_revision_id;
$function$;

