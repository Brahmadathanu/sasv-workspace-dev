create or replace function public.plm_sku_bom_revision_as_of(
  p_sku_id bigint,
  p_as_of date
)
returns public.plm_bom_revision
language plpgsql
stable
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_count integer;
  v_row public.plm_bom_revision%rowtype;
begin
  if p_sku_id is null then
    raise exception 'p_sku_id is required';
  end if;
  if p_as_of is null then
    raise exception 'p_as_of is required';
  end if;

  select count(*)::integer into v_count
  from public.plm_bom_revision r
  where r.sku_id = p_sku_id
    and r.status in ('APPROVED', 'SUPERSEDED')
    and r.effective_from <= p_as_of
    and (r.effective_to is null or r.effective_to >= p_as_of);

  if v_count > 1 then
    raise exception 'AMBIGUOUS_PM_BOM_REVISION: sku_id=% as_of=% matched % governed revisions',
      p_sku_id, p_as_of, v_count;
  end if;

  if v_count = 0 then
    return null;
  end if;

  select r.* into v_row
  from public.plm_bom_revision r
  where r.sku_id = p_sku_id
    and r.status in ('APPROVED', 'SUPERSEDED')
    and r.effective_from <= p_as_of
    and (r.effective_to is null or r.effective_to >= p_as_of);

  return v_row;
end;
$function$;

