create table if not exists costing.packing_labour_responsibility_rule (
  id bigint generated by default as identity primary key,
  route_family_id bigint not null references costing.production_route_family(id),
  responsibility_code text not null check (responsibility_code in ('SASV_INTERNAL_PACKING','EXTERNAL_FULLY_PACKED')),
  effective_from date not null,
  effective_to date null,
  status text not null default 'DRAFT' check (status in ('DRAFT','APPROVED','CANCELLED')),
  rationale text not null,
  approval_reference text null,
  created_at timestamptz not null default now(),
  created_by uuid null,
  updated_at timestamptz not null default now(),
  updated_by uuid null,
  check (effective_to is null or effective_to >= effective_from)
);

create index if not exists ix_packing_labour_responsibility_rule_family_dates
  on costing.packing_labour_responsibility_rule(route_family_id,effective_from,effective_to,status);

create or replace function costing.fn_validate_packing_labour_responsibility_rule(p_rule_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path=costing,public,pg_temp
as $$
declare
  r costing.packing_labour_responsibility_rule%rowtype;
  v_family_status text;
  v_overlap_count bigint;
  v_errors jsonb := '[]'::jsonb;
begin
  select * into r from costing.packing_labour_responsibility_rule where id=p_rule_id;
  if not found then
    return jsonb_build_object('valid',false,'errors',jsonb_build_array('Rule not found'));
  end if;

  select status into v_family_status from costing.production_route_family where id=r.route_family_id;
  if v_family_status is distinct from 'APPROVED' then
    v_errors:=v_errors||jsonb_build_array('Route family must be APPROVED');
  end if;

  select count(*) into v_overlap_count
  from costing.packing_labour_responsibility_rule x
  where x.id<>r.id
    and x.route_family_id=r.route_family_id
    and x.status='APPROVED'
    and daterange(x.effective_from,coalesce(x.effective_to,'infinity'::date),'[]') &&
        daterange(r.effective_from,coalesce(r.effective_to,'infinity'::date),'[]');

  if v_overlap_count>0 then
    v_errors:=v_errors||jsonb_build_array('Approved effective-date overlap exists for this route family');
  end if;

  if r.responsibility_code='EXTERNAL_FULLY_PACKED' and btrim(coalesce(r.rationale,''))='' then
    v_errors:=v_errors||jsonb_build_array('External fully packed responsibility requires rationale');
  end if;

  return jsonb_build_object(
    'valid',jsonb_array_length(v_errors)=0,
    'rule_id',r.id,
    'route_family_id',r.route_family_id,
    'responsibility_code',r.responsibility_code,
    'effective_from',r.effective_from,
    'effective_to',r.effective_to,
    'status',r.status,
    'approved_overlap_count',v_overlap_count,
    'errors',v_errors
  );
end $$;